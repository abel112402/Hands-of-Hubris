/** Unreal's FKey name of a planned key, mouse button or gamepad button; undefined when unknown. */
export function unrealKey(device: 'key' | 'mouse' | 'gamepad', text: string): string | undefined {
  const t = text.trim().toLowerCase()
  if (device === 'mouse') return MOUSE[t]
  if (device === 'gamepad') return PAD[t]
  if (/^[a-z]$/.test(t)) return t.toUpperCase()
  if (/^[0-9]$/.test(t)) return DIGITS[Number(t)]
  if (/^f([1-9]|1[0-2])$/.test(t)) return t.toUpperCase()
  return KEYS[t]
}

const assetName = (prefix: string, words: string[]) => `${prefix}_${words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('')}`

/** What the bridge needs to make the Enhanced Input assets (goes into Meta/planner-types.json). */
export function inputPlan(ir: EngineIR) {
  const categories = [...new Set(ir.input.actions.map((a) => a.category))]
  return categories.map((cat) => ({
    category: cat,
    context: assetName('IMC', cat.split(/\W+/).filter(Boolean)),
    actions: ir.input.actions
      .filter((a) => a.category === cat)
      .map((a) => ({
        name: a.name,
        asset: assetName('IA', a.words),
        keys: ([['key', a.key], ['mouse', a.mouse], ['gamepad', a.gamepad]] as const).flatMap(([d, t]) => (t && unrealKey(d, t) ? [unrealKey(d, t)!] : [])),
        ...(a.mode && { mode: a.mode }),
      })),
  }))
}

export function inputFiles(ir: EngineIR, n: UnrealNames): EmittedFile[] {
  if (!ir.input.actions.length) return []
  const plan = inputPlan(ir)
  const lines = [
    ...HEADER(ir, 'input actions'),
    '#pragma once',
    '',
    '#include "CoreMinimal.h"',
    '',
    '/**',
    ' * The plan’s controls (UI/UX › Controls) as Enhanced Input assets, which the planner bridge makes under',
    ` * ${INPUT_ROOT}: one Input Action per control, one Input Mapping Context per category. Load them by these paths,`,
    ' * e.g. LoadObject<UInputAction>(nullptr, PlannerInput::Movement::Jump).',
    ' */',
    'namespace PlannerInput',
    '{',
  ]
  const used = new Set<string>()
  for (const c of plan) {
    let ns = n.identifier(c.category.split(/\W+/).filter(Boolean)) || 'Actions'
    for (let i = 2; used.has(ns); i++) ns = `${n.identifier(c.category.split(/\W+/).filter(Boolean))}${i}`
    used.add(ns)
    lines.push(`\tnamespace ${ns}`, '\t{', `\t\tconstexpr const TCHAR* Context = ${n.cppString(`${INPUT_ROOT}/${c.context}.${c.context}`)};`)
    const names = new Set<string>(['Context'])
    for (const a of c.actions) {
      const action = ir.input.actions.find((x) => x.name === a.name)!
      let id = n.identifier(action.words) || 'Action'
      for (let i = 2; names.has(id); i++) id = `${n.identifier(action.words)}${i}`
      names.add(id)
      lines.push(`\t\t/** ${comment(`${a.name}${a.keys.length ? `: ${a.keys.join(', ')}` : ''}${a.mode ? ` (${a.mode.toLowerCase()})` : ''}.`)} */`, `\t\tconstexpr const TCHAR* ${id} = ${n.cppString(`${INPUT_ROOT}/${a.asset}.${a.asset}`)};`)
    }
    lines.push('\t}')
  }
  lines.push('}', '')
  return [{ path: `${n.gen}PlannerInput.h`, content: lines.join('\n') }]
}

