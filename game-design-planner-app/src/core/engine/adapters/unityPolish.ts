import type { EmittedFile } from '../adapter'
import type { EngineIR } from '../ir'
import type { UnityNames } from './unityExtras'

/**
 * Unity output for the polish ideas (plans/UNITY_INTEGRATION_PLAN.md § 7): a sampler for the performance budgets
 * (I10), audio events from Audio Direction (I12) and an EditMode test that holds the assemblies to the planned module
 * dependencies (I18). The pseudo-locale (I15) is made by the bridge's Localization step.
 */

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const HEADER = (ir: EngineIR, what: string) => ['// <auto-generated>', `//   Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name}”: ${what}.`, '//   Do not edit: the next import overwrites this file.', '// </auto-generated>']
const indent = (lines: string[], n = 4) => lines.map((l) => (l ? ' '.repeat(n) + l : l))
const wrap = (ir: EngineIR, n: UnityNames, what: string, usings: string[], body: string[]) => [...HEADER(ir, what), ...usings.map((u) => `using ${u};`), '', `namespace ${n.ns}`, '{', ...indent(body), '}', ''].join('\n')

// ---- I10: performance budgets ----

/** How a probe reads its value, as C#: [recorder setup or null, value expression from the recorder or a frame]. */
const PROBES: Record<string, { category?: string; counter?: string }> = {
  memory: { category: 'Memory', counter: 'Total Used Memory' },
  drawCalls: { category: 'Render', counter: 'Draw Calls Count' },
  batches: { category: 'Render', counter: 'Batches Count' },
  triangles: { category: 'Render', counter: 'Triangles Count' },
}
const memoryScale = (unit: string) => (/^g/i.test(unit) ? '1.0 / (1024.0 * 1024.0 * 1024.0)' : /^m/i.test(unit) ? '1.0 / (1024.0 * 1024.0)' : /^k/i.test(unit) ? '1.0 / 1024.0' : '1.0')

export function budgetFiles(ir: EngineIR, n: UnityNames): EmittedFile[] {
  const budgets = ir.budgets
  if (!budgets.length) return []
  const auto = budgets.filter((b) => b.probe !== 'custom')
  const custom = budgets.filter((b) => b.probe === 'custom')
  // Each recorder-based budget gets the next recorder slot.
  let slot = 0
  const samplers = auto.map((b) => {
    if (b.probe === 'frameTime') return { setup: null as string | null, read: 'Time.unscaledDeltaTime * 1000.0', key: b.key }
    const p = PROBES[b.probe]
    const scale = b.probe === 'memory' ? ` * (${memoryScale(b.unit)})` : ''
    const i = slot++
    return { setup: `ProfilerRecorder.StartNew(ProfilerCategory.${p.category}, ${n.csString(p.counter!)})`, read: `recorders[${i}].LastValue${scale}`, key: b.key }
  })
  const body = [
    '/// <summary>',
    '/// Measures the planned performance budgets (Technical › Performance) while the game runs, in the editor and in',
    '/// development builds: frame time, memory, draw calls, batches and triangles by itself; the others when the game',
    '/// calls Record(key, value), e.g. PlannerBudgets.Record(PlannerBudgets.' + (custom[0] ? `Keys.${n.identifier(custom[0].words).replace(/^@/, '')}` : 'Keys.X') + ', ms).',
    '/// The mean, minimum and maximum per key are saved to &lt;persistentDataPath&gt;/hoh-planner-budgets.json when the game',
    '/// quits; the planner bridge puts them into the report, and the planner compares them with the budgets.',
    '/// Define HOH_NO_PLANNER_BUDGETS to leave the sampler out.',
    '/// </summary>',
    'public sealed class PlannerBudgets : MonoBehaviour',
    '{',
    '    public const string FileName = "hoh-planner-budgets.json";',
    '',
    '    /// <summary>The metric key of each budget, as the planner reports it.</summary>',
    '    public static class Keys',
    '    {',
    ...budgets.map((b) => `        /// <summary>${xml(`${b.name}${b.platform ? ` (${b.platform})` : ''}: ${b.metric || b.probe}${b.target !== undefined ? `, target ${b.target} ${b.unit}` : ''}.`)}</summary>\n        public const string ${n.identifier(b.words).replace(/^@/, '')} = ${n.csString(b.key)};`).flatMap((s) => s.split('\n')),
    '    }',
    '',
    '    [Serializable]',
    '    private sealed class Summary',
    '    {',
    '        public string key;',
    '        public int samples;',
    '        public double sum;',
    '        public double min;',
    '        public double max;',
    '        public string build;',
    '        public string lastAt;',
    '    }',
    '',
    '    [Serializable]',
    '    private sealed class Store',
    '    {',
    '        public List<Summary> metrics = new List<Summary>();',
    '    }',
    '',
    '    private static readonly Dictionary<string, Summary> Data = new Dictionary<string, Summary>();',
    '    private ProfilerRecorder[] recorders = Array.Empty<ProfilerRecorder>();',
    '    private float warmUp = 2f;',
    '',
    '    /// <summary>Adds one sample under a budget key (for the budgets the sampler cannot measure by itself).</summary>',
    '    public static void Record(string key, double value)',
    '    {',
    '        if (string.IsNullOrEmpty(key) || double.IsNaN(value) || double.IsInfinity(value)) return;',
    '        if (!Data.TryGetValue(key, out var s)) Data[key] = s = new Summary { key = key, min = value, max = value };',
    '        s.samples++;',
    '        s.sum += value;',
    '        s.min = Math.Min(s.min, value);',
    '        s.max = Math.Max(s.max, value);',
    '    }',
    '',
    '#if (UNITY_EDITOR || DEVELOPMENT_BUILD) && !HOH_NO_PLANNER_BUDGETS',
    '    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]',
    '    private static void Create()',
    '    {',
    '        var go = new GameObject("PlannerBudgets") { hideFlags = HideFlags.HideInHierarchy };',
    '        DontDestroyOnLoad(go);',
    '        go.AddComponent<PlannerBudgets>();',
    '    }',
    '#endif',
    '',
    '    private void OnEnable()',
    '    {',
    `        recorders = new ProfilerRecorder[${samplers.filter((s) => s.setup).length}];`,
    ...samplers.filter((s) => s.setup).map((s, j) => `        recorders[${j}] = ${s.setup};`),
    '    }',
    '',
    '    private void OnDisable()',
    '    {',
    '        foreach (var r in recorders) r.Dispose();',
    '    }',
    '',
    '    private void Update()',
    '    {',
    '        // The first seconds (loading, shader warm-up) are not what the budget is about.',
    '        if ((warmUp -= Time.unscaledDeltaTime) > 0) return;',
    ...samplers.map((s) => `        Record(${n.csString(s.key)}, ${s.read});`),
    '    }',
    '',
    '    private void OnApplicationQuit() => Save();',
    '',
    '    /// <summary>Adds this session’s samples to the file (summed with the sessions before).</summary>',
    '    public static void Save()',
    '    {',
    '        if (Data.Count == 0) return;',
    '        var path = Path.Combine(Application.persistentDataPath, FileName);',
    '        var store = File.Exists(path) ? JsonUtility.FromJson<Store>(File.ReadAllText(path)) ?? new Store() : new Store();',
    '        foreach (var s in Data.Values)',
    '        {',
    '            var old = store.metrics.Find(m => m.key == s.key);',
    '            if (old == null) store.metrics.Add(old = new Summary { key = s.key, min = s.min, max = s.max });',
    '            old.samples += s.samples;',
    '            old.sum += s.sum;',
    '            old.min = Math.Min(old.min, s.min);',
    '            old.max = Math.Max(old.max, s.max);',
    '            old.build = Application.version;',
    '            old.lastAt = DateTime.UtcNow.ToString("o");',
    '        }',
    '        File.WriteAllText(path, JsonUtility.ToJson(store, true));',
    '        Data.Clear();',
    '    }',
    '}',
  ]
  return [{ path: 'Scripts/Generated/Perf/PlannerBudgets.cs', content: wrap(ir, n, 'performance budgets', ['System', 'System.Collections.Generic', 'System.IO', 'Unity.Profiling', 'UnityEngine'], body) }]
}

// ---- I12: audio events ----

export function audioFiles(ir: EngineIR, n: UnityNames): EmittedFile[] {
  const events = ir.audio.events
  if (!events.length) return []
  const so = [
    '/// <summary>',
    '/// One sound of the plan (Audio Direction › Music / Sound effects): the clips you assign, and the planned volume,',
    '/// pitch variation, looping and 3D setting. The planner bridge makes one asset per event under Audio/ and keeps the',
    '/// planned values in step; the clips are yours.',
    '/// </summary>',
    '[CreateAssetMenu(menuName = ' + n.csString(`${ir.project.name || 'Game'}/Audio event`) + ', fileName = "AudioEvent")]',
    'public sealed class PlannerAudioEvent : ScriptableObject',
    '{',
    '    public string plannerId;',
    '    public PlannerAudioKind kind;',
    '    [Tooltip("Assign one or more; Play picks one at random.")]',
    '    public AudioClip[] clips = new AudioClip[0];',
    '    [Range(0, 1)] public float volume = 1;',
    '    [Tooltip("± fraction of pitch, picked per play.")] [Range(0, 0.5f)] public float pitchVariation;',
    '    public bool loop;',
    '    public bool spatial;',
    '    [TextArea] public string notes;',
    '',
    '    /// <summary>Plays one of the clips on the source with the planned settings.</summary>',
    '    public void Play(AudioSource source)',
    '    {',
    '        if (source == null || clips == null || clips.Length == 0) return;',
    '        source.clip = clips[UnityEngine.Random.Range(0, clips.Length)];',
    '        source.volume = volume;',
    '        source.pitch = 1f + UnityEngine.Random.Range(-pitchVariation, pitchVariation);',
    '        source.loop = loop;',
    '        source.spatialBlend = spatial ? 1f : 0f;',
    '        source.Play();',
    '    }',
    '',
    '#if UNITY_EDITOR',
    '    /// <summary>Called by the planner bridge: one asset per planned event under &lt;root&gt;/Audio/, found again by planner ID.</summary>',
    '    public static void PlannerCreateOrUpdate(string root)',
    '    {',
    '        var folder = $"{root}/Audio";',
    '        if (!UnityEditor.AssetDatabase.IsValidFolder(folder)) UnityEditor.AssetDatabase.CreateFolder(root, "Audio");',
    '        var existing = new Dictionary<string, PlannerAudioEvent>();',
    '        foreach (var guid in UnityEditor.AssetDatabase.FindAssets("t:PlannerAudioEvent", new[] { folder }))',
    '        {',
    '            var a = UnityEditor.AssetDatabase.LoadAssetAtPath<PlannerAudioEvent>(UnityEditor.AssetDatabase.GUIDToAssetPath(guid));',
    '            if (a != null && !string.IsNullOrEmpty(a.plannerId)) existing[a.plannerId] = a;',
    '        }',
    '        foreach (var e in PlannerAudioEvents.All)',
    '        {',
    '            if (!existing.TryGetValue(e.Id, out var asset))',
    '            {',
    '                asset = CreateInstance<PlannerAudioEvent>();',
    '                asset.plannerId = e.Id;',
    '                UnityEditor.AssetDatabase.CreateAsset(asset, $"{folder}/{e.File}.asset");',
    '            }',
    '            asset.kind = e.Kind;',
    '            asset.volume = e.Volume;',
    '            asset.pitchVariation = e.Pitch;',
    '            asset.loop = e.Loop;',
    '            asset.spatial = e.Spatial;',
    '            asset.notes = e.Notes;',
    '            UnityEditor.EditorUtility.SetDirty(asset);',
    '        }',
    '        UnityEditor.AssetDatabase.SaveAssets();',
    '    }',
    '#endif',
    '}',
  ]
  const used = new Set<string>()
  const files = events.map((e) => {
    let f = n.identifier(e.words).replace(/^@/, '') || 'Sound'
    for (let i = 2; used.has(f); i++) f = `${n.identifier(e.words).replace(/^@/, '')}${i}`
    used.add(f)
    return f
  })
  const table = [
    '/// <summary>Music and sound effects.</summary>',
    'public enum PlannerAudioKind',
    '{',
    '    Music,',
    '    Sfx,',
    '}',
    '',
    '/// <summary>The planned audio events (Audio Direction), as the bridge turns them into PlannerAudioEvent assets.</summary>',
    'public static class PlannerAudioEvents',
    '{',
    '    public readonly struct Entry',
    '    {',
    '        public readonly string Id, File, Name, Notes;',
    '        public readonly PlannerAudioKind Kind;',
    '        public readonly float Volume, Pitch;',
    '        public readonly bool Loop, Spatial;',
    '',
    '        public Entry(string id, string file, string name, PlannerAudioKind kind, float volume, float pitch, bool loop, bool spatial, string notes)',
    '        {',
    '            Id = id;',
    '            File = file;',
    '            Name = name;',
    '            Kind = kind;',
    '            Volume = volume;',
    '            Pitch = pitch;',
    '            Loop = loop;',
    '            Spatial = spatial;',
    '            Notes = notes;',
    '        }',
    '    }',
    '',
    '    public static readonly Entry[] All =',
    '    {',
    ...events.map((e, i) => `        new Entry(${n.csString(e.id)}, ${n.csString(files[i])}, ${n.csString(e.name)}, PlannerAudioKind.${e.kind === 'music' ? 'Music' : 'Sfx'}, ${e.volume}f, ${e.pitch}f, ${e.loop ? 'true' : 'false'}, ${e.spatial ? 'true' : 'false'}, ${n.csString([e.notes, e.when.length ? `Plays: ${e.when.join(', ')}.` : ''].filter(Boolean).join(' '))}),`),
    '    };',
    '}',
  ]
  return [
    { path: 'Scripts/Generated/Audio/PlannerAudioEvent.cs', content: wrap(ir, n, 'audio event', ['System.Collections.Generic', 'UnityEngine'], so) },
    { path: 'Scripts/Generated/Audio/PlannerAudioEvents.cs', content: wrap(ir, n, 'audio events of Audio Direction', [], table) },
  ]
}

// ---- I18: architecture guard ----

export function architectureTest(ir: EngineIR, n: UnityNames): EmittedFile[] {
  const modules = ir.setup.modules
  if (modules.length < 2) return []
  const asm = (m: (typeof modules)[number]) => m.assembly || m.words.map((w) => n.identifier([w]).replace(/^@/, '')).join('.')
  const byId = new Map(modules.map((m) => [m.id, m]))
  const planned = modules.map((m) => `        [${n.csString(asm(m))}] = new string[] { ${m.dependsOn.map((d) => byId.get(d)).filter((x): x is (typeof modules)[number] => !!x).map((d) => n.csString(asm(d))).join(', ')} },`)
  const body = [
    '/// <summary>',
    '/// Holds the real assemblies to the Architecture: a planned module’s assembly may reference only the modules it',
    '/// depends on in the plan (and anything that is not a planned module, such as Unity’s packages or the generated code).',
    '/// </summary>',
    'public class PlannerArchitecture',
    '{',
    '    private static readonly Dictionary<string, string[]> Planned = new Dictionary<string, string[]>',
    '    {',
    ...planned,
    '    };',
    '',
    '    [Serializable]',
    '    private sealed class Asmdef',
    '    {',
    '        public string name;',
    '        public string[] references;',
    '    }',
    '',
    '    private static Asmdef Read(string path) => File.Exists(path) ? JsonUtility.FromJson<Asmdef>(File.ReadAllText(path)) : null;',
    '',
    '    [Test]',
    '    public void AssembliesReferenceOnlyThePlannedModules()',
    '    {',
    '        var problems = new List<string>();',
    '        var found = 0;',
    '        foreach (var guid in AssetDatabase.FindAssets("t:AssemblyDefinitionAsset"))',
    '        {',
    '            var asmdef = Read(AssetDatabase.GUIDToAssetPath(guid));',
    '            if (asmdef == null || asmdef.name == null || !Planned.TryGetValue(asmdef.name, out var allowed)) continue;',
    '            found++;',
    '            foreach (var reference in asmdef.references ?? new string[0])',
    '            {',
    '                var target = reference.StartsWith("GUID:", StringComparison.Ordinal) ? Read(AssetDatabase.GUIDToAssetPath(reference.Substring(5)))?.name : reference;',
    '                if (target != null && target != asmdef.name && Planned.ContainsKey(target) && Array.IndexOf(allowed, target) < 0) problems.Add($"{asmdef.name} → {target}");',
    '            }',
    '        }',
    '        if (found == 0) Assert.Ignore("No assembly of a planned module yet: Tools ▸ Game Design Planner ▸ Set up project creates them.");',
    '        if (problems.Count > 0) Assert.Fail("These assemblies reference modules the Architecture does not let them use: " + string.Join(", ", problems) + ". Change the code, or the module’s Depends on in the plan.");',
    '    }',
    '}',
  ]
  return [{ path: 'Tests/Editor/PlannerArchitecture.cs', content: [...HEADER(ir, 'architecture guard'), 'using System;', 'using System.Collections.Generic;', 'using System.IO;', 'using NUnit.Framework;', 'using UnityEditor;', 'using UnityEngine;', '', `namespace ${n.root}.PlannerTests`, '{', ...indent(body), '}', ''].join('\n') }]
}
