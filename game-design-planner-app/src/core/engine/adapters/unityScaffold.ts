const KEYS: Record<string, string> = {
  space: 'space', shift: 'leftShift', lshift: 'leftShift', rshift: 'rightShift', ctrl: 'leftCtrl', control: 'leftCtrl', alt: 'leftAlt', esc: 'escape', escape: 'escape',
  tab: 'tab', enter: 'enter', return: 'enter', backspace: 'backspace', up: 'upArrow', down: 'downArrow', left: 'leftArrow', right: 'rightArrow', delete: 'delete', home: 'home', end: 'end',
}
const MOUSE: Record<string, string> = { lmb: 'leftButton', rmb: 'rightButton', mmb: 'middleButton', wheel: 'scroll', scroll: 'scroll' }
const PAD: Record<string, string> = {
  a: 'buttonSouth', b: 'buttonEast', x: 'buttonWest', y: 'buttonNorth', cross: 'buttonSouth', circle: 'buttonEast', square: 'buttonWest', triangle: 'buttonNorth',
  lb: 'leftShoulder', rb: 'rightShoulder', l1: 'leftShoulder', r1: 'rightShoulder', lt: 'leftTrigger', rt: 'rightTrigger', l2: 'leftTrigger', r2: 'rightTrigger',
  ls: 'leftStickPress', rs: 'rightStickPress', l3: 'leftStickPress', r3: 'rightStickPress', start: 'start', options: 'start', menu: 'start', select: 'select', back: 'select', view: 'select', share: 'select',
  'dpad up': 'dpad/up', 'dpad down': 'dpad/down', 'dpad left': 'dpad/left', 'dpad right': 'dpad/right',
}

/** An Input System control path for a planned key, mouse button or gamepad button; undefined when unknown. */
export function controlPath(device: 'key' | 'mouse' | 'gamepad', text: string): string | undefined {
  const t = text.trim().toLowerCase()
  if (device === 'mouse') return MOUSE[t] && `<Mouse>/${MOUSE[t]}`
  if (device === 'gamepad') return PAD[t] && `<Gamepad>/${PAD[t]}`
  if (/^[a-z0-9]$/.test(t)) return `<Keyboard>/${t}`
  if (/^f([1-9]|1[0-2])$/.test(t)) return `<Keyboard>/${t}`
  return KEYS[t] && `<Keyboard>/${KEYS[t]}`
}

/** Planned keys and buttons the export cannot turn into a binding. */
export function inputIssues(ir: EngineIR): EngineIssue[] {
  const out: EngineIssue[] = []
  for (const a of ir.input.actions)
    for (const [device, text] of [['key', a.key], ['mouse', a.mouse], ['gamepad', a.gamepad]] as const)
      if (text && !controlPath(device, text)) out.push({ level: 'info', code: 'input.binding', message: `Control ${a.name}: “${text}” is not a ${device === 'key' ? 'key' : device === 'mouse' ? 'mouse button' : 'gamepad button'} the export knows; bind it in the Input Actions editor.` })
  return out
}

/** `extra`: action maps beyond the plan's categories (the playable prototype's, unityGameplay.ts). */
export function inputFiles(ir: EngineIR, n: UnityNames, extra: Record<string, unknown>[] = []): EmittedFile[] {
  const actions = ir.input.actions
  if (!actions.length && !extra.length) return []
  const categories = [...new Set(actions.map((a) => a.category))]
  const maps = categories.map((cat) => {
    const list = actions.filter((a) => a.category === cat)
    const bindings = list.flatMap((a) =>
      (
        [
          ['key', a.key, 'Keyboard&Mouse'],
          ['mouse', a.mouse, 'Keyboard&Mouse'],
          ['gamepad', a.gamepad, 'Gamepad'],
        ] as const
      ).flatMap(([device, text, group]) => {
        if (!text) return []
        const path = controlPath(device, text)
        if (!path) return []
        return [{ name: '', id: guid(`${a.id}:${device}`), path, interactions: '', processors: '', groups: group, action: a.name, isComposite: false, isPartOfComposite: false }]
      }),
    )
    return {
      name: cat,
      id: guid(`map:${cat}`),
      actions: list.map((a) => ({ name: a.name, type: 'Button', id: guid(a.id), expectedControlType: 'Button', processors: '', interactions: '', initialStateCheck: false })),
      bindings,
    }
  })
  const asset = {
    name: n.root,
    maps: [...maps, ...extra],
    controlSchemes: [
      { name: 'Keyboard&Mouse', bindingGroup: 'Keyboard&Mouse', devices: [{ devicePath: '<Keyboard>', isOptional: false, isOR: false }, { devicePath: '<Mouse>', isOptional: false, isOR: false }] },
      { name: 'Gamepad', bindingGroup: 'Gamepad', devices: [{ devicePath: '<Gamepad>', isOptional: false, isOR: false }] },
    ],
  }
  const used = new Set<string>()
  const cls = (s: string) => {
    let c = n.identifier(s.split(/\W+/).filter(Boolean)).replace(/^@/, '') || 'Actions'
    for (let i = 2; used.has(c); i++) c = `${n.identifier(s.split(/\W+/).filter(Boolean)).replace(/^@/, '')}${i}`
    used.add(c)
    return c
  }
  const body: string[] = [
    '/// <summary>',
    '/// The plan’s controls (UI/UX › Controls) in Input/' + n.root + '.inputactions: one action map per category. Find an action with',
    '/// inputActionAsset.FindAction(PlannerInput.Movement.Jump); the names stay valid as long as the plan does.',
    '/// </summary>',
    'public static class PlannerInput',
    '{',
    `    public const string AssetName = ${n.csString(n.root)};`,
  ]
  for (const cat of categories) {
    const c = cls(cat)
    const names = new Set<string>(['Map'])
    body.push('', `    public static class ${c}`, '    {', `        public const string Map = ${n.csString(cat)};`)
    for (const a of actions.filter((x) => x.category === cat)) {
      let id = n.identifier(a.words).replace(/^@/, '') || 'Action'
      for (let i = 2; names.has(id); i++) id = `${n.identifier(a.words).replace(/^@/, '')}${i}`
      names.add(id)
      const doc = [a.key && `key ${a.key}`, a.mouse && `mouse ${a.mouse}`, a.gamepad && `gamepad ${a.gamepad}`, a.mode && `${a.mode.toLowerCase()}`, !a.rebindable && 'not rebindable', a.contexts.length && `only on ${a.contexts.map((s) => ir.ui.screens.find((x) => x.id === s)?.name ?? s).join(', ')}`].filter(Boolean).join(', ')
      body.push(`        /// <summary>${xml(`${a.name}${doc ? ` (${doc})` : ''}.`)}</summary>`, `        public const string ${id} = ${n.csString(`${cat}/${a.name}`)};`)
    }
    body.push('    }')
  }
  body.push('}')
  return [
    { path: `Input/${n.root}.inputactions`, content: JSON.stringify(asset, null, 4) + '\n' },
    { path: 'Scripts/Generated/Input/PlannerInput.cs', content: [...HEADER(ir, 'input actions'), `namespace ${n.ns}`, '{', ...indent(body), '}', ''].join('\n') },
  ]
}

// ---- I8: screens and navigation ----

const screenIds = (ir: EngineIR, n: UnityNames) => {
  const used = new Set<string>()
  return new Map(
    ir.ui.screens.map((s) => {
      let id = n.identifier(s.words).replace(/^@/, '') || 'Screen'
      for (let i = 2; used.has(id); i++) id = `${n.identifier(s.words).replace(/^@/, '')}${i}`
      used.add(id)
      return [s.id, id]
    }),
  )
}
const pct = (v: number, of: number) => `${Math.round((v / of) * 10000) / 100}%`

function elementXml(e: IrScreenElement, ir: EngineIR, ids: Map<string, string>): string {
  const style = `position: absolute; left: ${pct(e.x, ir.ui.width)}; top: ${pct(e.y, ir.ui.height)}; width: ${pct(e.w, ir.ui.width)}; height: ${pct(e.h, ir.ui.height)};`
  const bind = e.bind ? `bind-${e.bind.source}${e.bind.id ? `-${e.bind.id}` : ''}` : ''
  const name = e.opens && ids.has(e.opens) ? `open-${ids.get(e.opens)}` : bind || `${e.kind}-${e.id}`
  const common = `name="${xmlAttr(name)}" class="planner-${xmlAttr(e.kind)}" style="${style}"`
  const text = e.text ? xmlAttr(e.text) : ''
  switch (e.kind) {
    case 'heading':
    case 'label':
    case 'text':
      return `<ui:Label ${common} text="${text}" />`
    case 'button':
    case 'iconButton':
      return `<ui:Button ${common} text="${text}" />`
    case 'statBar':
      return `<ui:ProgressBar ${common} title="${xmlAttr(e.bind?.id ?? text)}" value="50" />`
    case 'slider':
      return `<ui:Slider ${common} label="${text}" low-value="0" high-value="100" />`
    case 'checkbox':
      return `<ui:Toggle ${common} label="${text}" />`
    case 'dropdown':
      return `<ui:DropdownField ${common} label="${text}" />`
    default:
      return text ? `<ui:VisualElement ${common}><ui:Label text="${text}" /></ui:VisualElement>` : `<ui:VisualElement ${common} />`
  }
}

function screenUxml(s: IrScreen, ir: EngineIR, ids: Map<string, string>): string {
  return [
    `<!-- Generated by Game Design Planner from “${xml(ir.project.name)}”: the screen ${xml(s.name)} (${xml(s.kind)}), laid out as planned in UI/UX › Screens. The next import replaces it. -->`,
    '<ui:UXML xmlns:ui="UnityEngine.UIElements" editor-extension-mode="False">',
    '    <Style src="../PlannerUI.uss" />',
    `    <ui:VisualElement name="screen-${xmlAttr(ids.get(s.id)!)}" class="planner-screen planner-screen--${xmlAttr(s.kind.toLowerCase().replace(/\W+/g, '-'))}" picking-mode="Ignore">`,
    ...s.elements.map((e) => `        ${elementXml(e, ir, ids)}`),
    '    </ui:VisualElement>',
    '</ui:UXML>',
    '',
  ].join('\n')
}

