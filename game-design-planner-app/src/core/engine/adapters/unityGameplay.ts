const PAD_DEVICES = /gamepad|controller|xbox|playstation|ps[45]|steam deck|switch/i

export const wantsPlayer = (ir: EngineIR) => !!ir.gameplay?.systems.includes('movement')

/** The action map's name: “Prototype”, unless the plan has a control category of that name. */
export const prototypeMapName = (ir: EngineIR) => (ir.input.actions.some((a) => a.category === 'Prototype') ? 'Planner prototype' : 'Prototype')

const keyPath = (c?: RuntimeControl) => (c?.key ? controlPath('key', c.key) : undefined)
/** The keyboard control's name in the Input System (“w”, “space”), for tests. */
const keyName = (c?: RuntimeControl) => keyPath(c)?.replace('<Keyboard>/', '')

/** A stable GUID-shaped ID from text, as unityScaffold's action IDs. */
function guid(text: string): string {
  const h = (s: string) => {
    let x = 2166136261
    for (let i = 0; i < s.length; i++) x = Math.imul(x ^ s.charCodeAt(i), 16777619) >>> 0
    return x.toString(16).padStart(8, '0')
  }
  const hex = h(`proto:${text}`) + h(`1proto:${text}`) + h(`2proto:${text}`) + h(`3proto:${text}`)
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`
}

/** The prototype's action map for the .inputactions asset, or null when the plan chose no player movement. */
export function prototypeInputMap(ir: EngineIR): Record<string, unknown> | null {
  if (!wantsPlayer(ir)) return null
  const { move, interact, crafting, attack } = ir.gameplay!.input
  const parts = (['forward', 'back', 'left', 'right'] as const).flatMap((slot, i) => {
    const path = keyPath(move[slot])
    return path ? [{ name: ['up', 'down', 'left', 'right'][i], id: guid(`move:${slot}`), path, interactions: '', processors: '', groups: 'Keyboard&Mouse', action: 'Move', isComposite: false, isPartOfComposite: true }] : []
  })
  const bindings: Record<string, unknown>[] = []
  if (parts.length) bindings.push({ name: 'Keys', id: guid('move:composite'), path: '2DVector', interactions: '', processors: '', groups: '', action: 'Move', isComposite: true, isPartOfComposite: false }, ...parts)
  if (ir.input.devices.some((d) => PAD_DEVICES.test(d))) bindings.push({ name: '', id: guid('move:stick'), path: '<Gamepad>/leftStick', interactions: '', processors: '', groups: 'Gamepad', action: 'Move', isComposite: false, isPartOfComposite: false })
  const interactKey = keyPath(interact)
  if (interactKey) bindings.push({ name: '', id: guid('interact:key'), path: interactKey, interactions: '', processors: '', groups: 'Keyboard&Mouse', action: 'Interact', isComposite: false, isPartOfComposite: false })
  const interactPad = interact?.gamepad && controlPath('gamepad', interact.gamepad)
  if (interactPad) bindings.push({ name: '', id: guid('interact:pad'), path: interactPad, interactions: '', processors: '', groups: 'Gamepad', action: 'Interact', isComposite: false, isPartOfComposite: false })
  const attackKey = keyPath(attack)
  if (attackKey) bindings.push({ name: '', id: guid('attack:key'), path: attackKey, interactions: '', processors: '', groups: 'Keyboard&Mouse', action: 'Attack', isComposite: false, isPartOfComposite: false })
  const attackPad = attack?.gamepad && controlPath('gamepad', attack.gamepad)
  if (attackPad) bindings.push({ name: '', id: guid('attack:pad'), path: attackPad, interactions: '', processors: '', groups: 'Gamepad', action: 'Attack', isComposite: false, isPartOfComposite: false })
  const craftKey = keyPath(crafting)
  if (craftKey) bindings.push({ name: '', id: guid('crafting:key'), path: craftKey, interactions: '', processors: '', groups: 'Keyboard&Mouse', action: 'Crafting', isComposite: false, isPartOfComposite: false })
  const craftPad = crafting?.gamepad && controlPath('gamepad', crafting.gamepad)
  if (craftPad) bindings.push({ name: '', id: guid('crafting:pad'), path: craftPad, interactions: '', processors: '', groups: 'Gamepad', action: 'Crafting', isComposite: false, isPartOfComposite: false })
  return {
    name: prototypeMapName(ir),
    id: guid('map'),
    actions: [
      { name: 'Move', type: 'Value', id: guid('action:move'), expectedControlType: 'Vector2', processors: '', interactions: '', initialStateCheck: true },
      { name: 'Interact', type: 'Button', id: guid('action:interact'), expectedControlType: 'Button', processors: '', interactions: '', initialStateCheck: false },
      ...(crafting ? [{ name: 'Crafting', type: 'Button', id: guid('action:crafting'), expectedControlType: 'Button', processors: '', interactions: '', initialStateCheck: false }] : []),
      ...(attack ? [{ name: 'Attack', type: 'Button', id: guid('action:attack'), expectedControlType: 'Button', processors: '', interactions: '', initialStateCheck: false }] : []),
    ],
    bindings,
  }
}

/** Move controls without a key the export can bind: the player could not walk that way. */
export function gameplayIssues(ir: EngineIR): EngineIssue[] {
  if (!wantsPlayer(ir)) return []
  const out: EngineIssue[] = []
  const { move } = ir.gameplay!.input
  for (const [slot, label] of [['forward', 'Move forward'], ['back', 'Move back'], ['left', 'Move left'], ['right', 'Move right']] as const) {
    const c = move[slot]
    if (c && !keyPath(c)) out.push({ level: 'warning', code: 'unity.moveKey', message: `${c.name} (${label}): “${c.key ?? ''}” is not a keyboard key the export knows, so the Move stick has no ${label.toLowerCase().replace('move ', '')} key; set a key like W or Up.`, where: { doc: 'design.ui', section: 'controls', id: c.control, field: 'key' } })
  }
  return out
}

