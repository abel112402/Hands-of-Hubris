import { APP_VERSION } from '../model/types'
import { WORLD_DOC } from '../world'
import { mapOf } from '../location/schema'
import { locationJson } from '../location/export/json'
import { pascal, uniqueNames, type EmittedFile, type EngineAdapter, type EngineId } from './adapter'
import { getAdapter } from './adapters'
import { ENGINE_TARGETS } from './target'
import { buildIR, type EngineIR, type EngineIssue, type IrSchema } from './ir'
