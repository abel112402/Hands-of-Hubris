import type { EmittedFile } from '../adapter'
import type { EngineIR } from '../ir'
import type { UnrealNames } from './unrealExtras'

/**
 * Unreal output for the polish ideas (plans/UNITY_INTEGRATION_PLAN.md § 7), the counterparts of unityPolish.ts: a game
 * instance subsystem that samples the performance budgets (I10) and a data asset per planned sound (I12: the bridge
 * makes the assets from Meta/planner-types.json). The architecture guard (I18) is ProjectFiles/architecture.json, checked
 * by the bridge's Validate. Unreal has no planner localization step yet, so there is no pseudo-locale (I15).
 */

const HEADER = (ir: EngineIR, what: string) => [`// Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name.replace(/\*\//g, '* /')}”: ${what}.`, '// Do not edit: the next export replaces this file.']
const comment = (s: string) => s.replace(/\*\//g, '* /')

// ---- I10: performance budgets ----

/** What the subsystem reads for a budget it measures by itself; batches have no counter, so the game records them. */
const memoryScale = (unit: string) => (/^g/i.test(unit) ? ' / (1024.0 * 1024.0 * 1024.0)' : /^m/i.test(unit) ? ' / (1024.0 * 1024.0)' : /^k/i.test(unit) ? ' / 1024.0' : '')
const READ: Record<string, (unit: string) => string> = {
  frameTime: () => 'FrameMs',
  memory: (u) => `double(FPlatformMemory::GetStats().UsedPhysical)${memoryScale(u)}`,
  drawCalls: () => 'GNumDrawCallsRHI[0]',
  triangles: () => 'GNumPrimitivesDrawnRHI[0]',
}

/** The RHI counters need the RHI module (Generated/Dependencies.txt). */
export const budgetModules = (ir: EngineIR) => (ir.budgets.some((b) => b.probe === 'drawCalls' || b.probe === 'triangles') ? ['RHI'] : [])

export function budgetFiles(ir: EngineIR, n: UnrealNames): EmittedFile[] {
  const budgets = ir.budgets
  if (!budgets.length) return []
  const used = new Set<string>()
  const consts = budgets.map((b) => {
    let c = n.identifier(b.words) || 'Budget'
    for (let k = 2; used.has(c); k++) c = `${n.identifier(b.words)}${k}`
    used.add(c)
    return c
  })
  const custom = budgets.findIndex((b) => !READ[b.probe])
  const rhi = budgetModules(ir).length > 0
  const header = [
    ...HEADER(ir, 'performance budgets'),
    '#pragma once',
    '',
    '#include "CoreMinimal.h"',
    '#include "Subsystems/GameInstanceSubsystem.h"',
    '#include "Tickable.h"',
    '#include "PlannerBudgets.generated.h"',
    '',
    '/** The metric key of each planned budget (Technical › Performance), as the planner reports it. */',
    'namespace PlannerBudgetKeys',
    '{',
    ...budgets.flatMap((b, i) => [`\t/** ${comment(`${b.name}${b.platform ? ` (${b.platform})` : ''}: ${b.metric || b.probe}${b.target !== undefined ? `, target ${b.target} ${b.unit}` : ''}.`)} */`, `\tconstexpr const TCHAR* ${consts[i]} = TEXT(${JSON.stringify(b.key)});`]),
    '}',
    '',
    '/**',
    ' * Measures the planned performance budgets while the game runs (not in Shipping builds): frame time, memory, draw',
    ' * calls and triangles by itself; the others when the game calls',
    ` * UPlannerBudgets::Record(PlannerBudgetKeys::${consts[custom >= 0 ? custom : 0]}, Ms) or the Blueprint node Record Budget.`,
    ' * The mean, minimum and maximum per key are added to Saved/hoh-planner-budgets.json when the game instance shuts down;',
    ' * the bridge puts them into the report, and the planner compares them with the budgets. Define HOH_NO_PLANNER_BUDGETS=1',
    ' * to leave the sampler out.',
    ' */',
    'UCLASS()',
    `class ${n.api} UPlannerBudgets : public UGameInstanceSubsystem, public FTickableGameObject`,
    '{',
    '\tGENERATED_BODY()',
    '',
    'public:',
    '\t/** Adds one sample under a budget key (for the budgets the sampler cannot measure by itself). */',
    '\tUFUNCTION(BlueprintCallable, Category = "Planner|Budgets", meta = (DisplayName = "Record Budget"))',
    '\tstatic void Record(const FString& Key, float Value);',
    '',
    '\t/** Adds this session’s samples to the file (summed with the sessions before). */',
    '\tstatic void Save();',
    '',
    '\tstatic FString FilePath();',
    '',
    '\tvirtual bool ShouldCreateSubsystem(UObject* Outer) const override;',
    '\tvirtual void Deinitialize() override;',
    '',
    '\tvirtual void Tick(float DeltaTime) override;',
    '\tvirtual TStatId GetStatId() const override;',
    '\tvirtual bool IsTickableWhenPaused() const override { return true; }',
    '\tvirtual ETickableTickType GetTickableTickType() const override;',
    '',
    'private:',
    '\t/** The first seconds (loading, shader warm-up) are not what the budgets are about. */',
    '\tdouble WarmUp = 2.0;',
    '};',
    '',
  ]
  const cpp = [
    ...HEADER(ir, 'performance budgets'),
    '#include "PlannerBudgets.h"',
    '#include "Dom/JsonObject.h"',
    '#include "HAL/PlatformMemory.h"',
    '#include "Misc/App.h"',
    '#include "Misc/DateTime.h"',
    '#include "Misc/FileHelper.h"',
    '#include "Misc/Paths.h"',
    ...(rhi ? ['#include "RHI.h"'] : []),
    '#include "Serialization/JsonReader.h"',
    '#include "Serialization/JsonSerializer.h"',
    '#include "Serialization/JsonWriter.h"',
    '',
    'namespace',
    '{',
    '\tstruct FBudgetSummary',
    '\t{',
    '\t\tint64 Samples = 0;',
    '\t\tdouble Sum = 0, Min = 0, Max = 0;',
    '\t};',
    '',
    '\tTMap<FString, FBudgetSummary>& Data()',
    '\t{',
    '\t\tstatic TMap<FString, FBudgetSummary> Summaries;',
    '\t\treturn Summaries;',
    '\t}',
    '}',
    '',
    'FString UPlannerBudgets::FilePath()',
    '{',
    '\treturn FPaths::Combine(FPaths::ProjectSavedDir(), TEXT("hoh-planner-budgets.json"));',
    '}',
    '',
    'bool UPlannerBudgets::ShouldCreateSubsystem(UObject* Outer) const',
    '{',
    '#if UE_BUILD_SHIPPING || (defined(HOH_NO_PLANNER_BUDGETS) && HOH_NO_PLANNER_BUDGETS)',
    '\treturn false;',
    '#else',
    '\treturn Super::ShouldCreateSubsystem(Outer);',
    '#endif',
    '}',
    '',
    'ETickableTickType UPlannerBudgets::GetTickableTickType() const',
    '{',
    '\t// The class default object is no subsystem; only the real one samples.',
    '\treturn HasAnyFlags(RF_ClassDefaultObject) ? ETickableTickType::Never : ETickableTickType::Always;',
    '}',
    '',
    'TStatId UPlannerBudgets::GetStatId() const',
    '{',
    '\tRETURN_QUICK_DECLARE_CYCLE_STAT(UPlannerBudgets, STATGROUP_Tickables);',
    '}',
    '',
    'void UPlannerBudgets::Record(const FString& Key, float Value)',
    '{',
    '\tif (Key.IsEmpty() || !FMath::IsFinite(Value))',
    '\t{',
    '\t\treturn;',
    '\t}',
    '\tFBudgetSummary* S = Data().Find(Key);',
    '\tif (!S)',
    '\t{',
    '\t\tS = &Data().Add(Key, FBudgetSummary{ 0, 0, Value, Value });',
    '\t}',
    '\tS->Samples++;',
    '\tS->Sum += Value;',
    '\tS->Min = FMath::Min(S->Min, double(Value));',
    '\tS->Max = FMath::Max(S->Max, double(Value));',
    '}',
    '',
    'void UPlannerBudgets::Tick(float DeltaTime)',
    '{',
    '\t// FApp::GetDeltaTime is the real frame time, not scaled by time dilation.',
    '\tconst double FrameMs = FApp::GetDeltaTime() * 1000.0;',
    '\tif ((WarmUp -= FApp::GetDeltaTime()) > 0)',
    '\t{',
    '\t\treturn;',
    '\t}',
    ...budgets.flatMap((b, i) => (READ[b.probe] ? [`\tRecord(PlannerBudgetKeys::${consts[i]}, ${READ[b.probe](b.unit)});`] : [])),
    '}',
    '',
    'void UPlannerBudgets::Deinitialize()',
    '{',
    '\tSave();',
    '\tSuper::Deinitialize();',
    '}',
    '',
    'void UPlannerBudgets::Save()',
    '{',
    '\tif (Data().Num() == 0)',
    '\t{',
    '\t\treturn;',
    '\t}',
    '\tTSharedPtr<FJsonObject> Root;',
    '\tFString Text;',
    '\tif (FFileHelper::LoadFileToString(Text, *FilePath()))',
    '\t{',
    '\t\tFJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(Text), Root);',
    '\t}',
    '\tTMap<FString, TSharedPtr<FJsonObject>> Store;',
    '\tTArray<FString> Order;',
    '\tconst TArray<TSharedPtr<FJsonValue>>* Existing = nullptr;',
    '\tif (Root.IsValid() && Root->TryGetArrayField(TEXT("metrics"), Existing))',
    '\t{',
    '\t\tfor (const TSharedPtr<FJsonValue>& Item : *Existing)',
    '\t\t{',
    '\t\t\tconst TSharedPtr<FJsonObject>* Object = nullptr;',
    '\t\t\tFString ItemKey;',
    '\t\t\tif (Item.IsValid() && Item->TryGetObject(Object) && (*Object)->TryGetStringField(TEXT("key"), ItemKey) && !Store.Contains(ItemKey))',
    '\t\t\t{',
    '\t\t\t\tStore.Add(ItemKey, *Object);',
    '\t\t\t\tOrder.Add(ItemKey);',
    '\t\t\t}',
    '\t\t}',
    '\t}',
    '\tconst FString Now = FDateTime::UtcNow().ToIso8601();',
    '\tfor (const TPair<FString, FBudgetSummary>& Pair : Data())',
    '\t{',
    '\t\tTSharedPtr<FJsonObject>& Entry = Store.FindOrAdd(Pair.Key);',
    '\t\tconst bool bNew = !Entry.IsValid();',
    '\t\tif (bNew)',
    '\t\t{',
    '\t\t\tEntry = MakeShared<FJsonObject>();',
    '\t\t\tEntry->SetStringField(TEXT("key"), Pair.Key);',
    '\t\t\tOrder.Add(Pair.Key);',
    '\t\t}',
    '\t\tconst FBudgetSummary& S = Pair.Value;',
    '\t\tEntry->SetNumberField(TEXT("samples"), (bNew ? 0 : Entry->GetNumberField(TEXT("samples"))) + S.Samples);',
    '\t\tEntry->SetNumberField(TEXT("sum"), (bNew ? 0 : Entry->GetNumberField(TEXT("sum"))) + S.Sum);',
    '\t\tEntry->SetNumberField(TEXT("min"), bNew ? S.Min : FMath::Min(Entry->GetNumberField(TEXT("min")), S.Min));',
    '\t\tEntry->SetNumberField(TEXT("max"), bNew ? S.Max : FMath::Max(Entry->GetNumberField(TEXT("max")), S.Max));',
    '\t\tEntry->SetStringField(TEXT("build"), FApp::GetBuildVersion());',
    '\t\tEntry->SetStringField(TEXT("lastAt"), Now);',
    '\t}',
    '\tTArray<TSharedPtr<FJsonValue>> Metrics;',
    '\tfor (const FString& Key : Order)',
    '\t{',
    '\t\tMetrics.Add(MakeShared<FJsonValueObject>(Store[Key]));',
    '\t}',
    '\tconst TSharedRef<FJsonObject> Out = MakeShared<FJsonObject>();',
    '\tOut->SetArrayField(TEXT("metrics"), Metrics);',
    '\tFString Json;',
    '\tFJsonSerializer::Serialize(Out, TJsonWriterFactory<>::Create(&Json));',
    '\tFFileHelper::SaveStringToFile(Json, *FilePath());',
    '\tData().Reset();',
    '}',
    '',
  ]
  return [
    { path: `${n.gen}PlannerBudgets.h`, content: header.join('\n') },
    { path: `${n.gen}PlannerBudgets.cpp`, content: cpp.join('\n') },
  ]
}

// ---- I12: audio events ----

export const AUDIO_ROOT = '/Game/HoHPlanner/Audio'

/** The planned sounds for the bridge (Meta/planner-types.json), one data asset each. */
export function audioPlan(ir: EngineIR, n: UnrealNames, module: string) {
  if (!ir.audio.events.length) return undefined
  const used = new Set<string>()
  return {
    path: `/Script/${module}.PlannerAudioEvent`,
    folder: AUDIO_ROOT,
    events: ir.audio.events.map((e) => {
      const base = `AE_${n.identifier(e.words) || 'Sound'}`
      let asset = base
      for (let k = 2; used.has(asset); k++) asset = `${base}${k}`
      used.add(asset)
      return { plannerId: e.id, name: e.name, asset, kind: e.kind, volume: e.volume, pitch: e.pitch, loop: e.loop, spatial: e.spatial, notes: [e.notes, e.when.length ? `Plays: ${e.when.join(', ')}.` : ''].filter(Boolean).join(' ') }
    }),
  }
}

export function audioFiles(ir: EngineIR, n: UnrealNames): EmittedFile[] {
  if (!ir.audio.events.length) return []
  const header = [
    ...HEADER(ir, 'audio event'),
    '#pragma once',
    '',
    '#include "CoreMinimal.h"',
    '#include "Engine/DataAsset.h"',
    '#include "PlannerAudioEvent.generated.h"',
    '',
    'class UAudioComponent;',
    'class USoundBase;',
    '',
    'UENUM(BlueprintType)',
    'enum class EPlannerAudioKind : uint8',
    '{',
    '\tMusic,',
    '\tSfx,',
    '};',
    '',
    '/**',
    ' * One sound of the plan (Audio Direction › Music / Sound effects): the sounds you assign, and the planned volume, pitch',
    ` * variation, looping and 3D setting. The bridge makes one asset per event under ${AUDIO_ROOT} and keeps the planned`,
    ' * values in step; the sounds are yours. Looping is a property of the sound itself (Looping on a Sound Wave or Cue).',
    ' */',
    'UCLASS(BlueprintType)',
    `class ${n.api} UPlannerAudioEvent : public UPrimaryDataAsset`,
    '{',
    '\tGENERATED_BODY()',
    '',
    'public:',
    '\tUPROPERTY(VisibleAnywhere, BlueprintReadOnly, Category = "Planner")',
    '\tFString PlannerId;',
    '',
    '\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Audio")',
    '\tEPlannerAudioKind Kind = EPlannerAudioKind::Sfx;',
    '',
    '\t/** Assign one or more; Play picks one at random. */',
    '\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Audio")',
    '\tTArray<TObjectPtr<USoundBase>> Sounds;',
    '',
    '\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Audio", meta = (ClampMin = "0", ClampMax = "1"))',
    '\tfloat Volume = 1.f;',
    '',
    '\t/** ± fraction of pitch, picked per play. */',
    '\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Audio", meta = (ClampMin = "0", ClampMax = "0.5"))',
    '\tfloat PitchVariation = 0.f;',
    '',
    '\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Audio")',
    '\tbool bLoop = false;',
    '',
    '\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Audio")',
    '\tbool bSpatial = false;',
    '',
    '\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Audio", meta = (MultiLine = true))',
    '\tFString Notes;',
    '',
    '\t/** Plays one of the sounds with the planned settings: at Location when the event is 3D, else as 2D sound. */',
    '\tUFUNCTION(BlueprintCallable, Category = "Planner|Audio", meta = (WorldContext = "WorldContextObject"))',
    '\tUAudioComponent* Play(const UObject* WorldContextObject, FVector Location) const;',
    '};',
    '',
  ]
  const cpp = [
    ...HEADER(ir, 'audio event'),
    '#include "PlannerAudioEvent.h"',
    '#include "Components/AudioComponent.h"',
    '#include "Kismet/GameplayStatics.h"',
    '#include "Sound/SoundBase.h"',
    '',
    'UAudioComponent* UPlannerAudioEvent::Play(const UObject* WorldContextObject, FVector Location) const',
    '{',
    '\tif (Sounds.Num() == 0)',
    '\t{',
    '\t\treturn nullptr;',
    '\t}',
    '\tUSoundBase* Sound = Sounds[FMath::RandRange(0, Sounds.Num() - 1)];',
    '\tif (!Sound)',
    '\t{',
    '\t\treturn nullptr;',
    '\t}',
    '\tconst float Pitch = 1.f + FMath::FRandRange(-PitchVariation, PitchVariation);',
    '\treturn bSpatial',
    '\t\t? UGameplayStatics::SpawnSoundAtLocation(WorldContextObject, Sound, Location, FRotator::ZeroRotator, Volume, Pitch)',
    '\t\t: UGameplayStatics::SpawnSound2D(WorldContextObject, Sound, Volume, Pitch);',
    '}',
    '',
  ]
  return [
    { path: `${n.gen}PlannerAudioEvent.h`, content: header.join('\n') },
    { path: `${n.gen}PlannerAudioEvent.cpp`, content: cpp.join('\n') },
  ]
}
