/**
 * Unity output for the scaffolding ideas (plans/UNITY_INTEGRATION_PLAN.md § 7): the Input System action asset from
 * UI/UX › Controls (I13), UI Toolkit screens with a router that follows the planned Screen flow (I8), and the
 * planner's state graphs as typed state machines (I4). Generated code needs no package beyond Unity's own UI Toolkit;
 * the .inputactions file is read by the Input System package when the project has it.
 */

const xmlAttr = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const HEADER = (ir: EngineIR, what: string) => ['// <auto-generated>', `//   Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name}”: ${what}.`, '//   Do not edit: the next import overwrites this file.', '// </auto-generated>']
const indent = (lines: string[], n = 4) => lines.map((l) => (l ? ' '.repeat(n) + l : l))

/** A stable GUID-shaped ID from text (FNV-1a), so the same plan gives the same action IDs. */
function guid(text: string): string {
  const h = (s: string) => {
    let x = 2166136261
    for (let i = 0; i < s.length; i++) x = Math.imul(x ^ s.charCodeAt(i), 16777619) >>> 0
    return x.toString(16).padStart(8, '0')
  }
  const hex = h(text) + h(`1${text}`) + h(`2${text}`) + h(`3${text}`)
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`
}

