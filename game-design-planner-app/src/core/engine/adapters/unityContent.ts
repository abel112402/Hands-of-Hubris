    '        var steps = new List<int>();',
    '        for (var v = 1; v < PlannerSave.Version; v++)',
    '        {',
    '            var from = v;',
    '            PlannerSave.AddMigration(from, f => steps.Add(from));',
    '        }',
    '        parts.ForEach(p => p.State = "now");',
    '        Assert.IsTrue(PlannerSave.Load("old"));',
    '        CollectionAssert.AreEqual(Enumerable.Range(1, PlannerSave.Version - 1).ToList(), steps);',
    '        foreach (var p in parts) Assert.AreEqual(PlannerSaveKeys.Since[p.SaveKey] == 1 ? "old" : "now", p.State, p.SaveKey);',
