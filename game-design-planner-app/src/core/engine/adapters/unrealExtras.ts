import type { EmittedFile } from '../adapter'
import type { EngineIR, IrSchema } from '../ir'
import type { IrCheat, IrParam } from '../irExtras'

/**
 * Unreal output for the integration ideas (plans/UNITY_INTEGRATION_PLAN.md § 7), the counterparts of unityExtras.ts:
 * the Architecture's channels (native multicast delegates for the event buses, a data asset with a dynamic delegate per
 * ScriptableObject-style channel), typed telemetry (a Blueprint function library writing Saved/hoh-telemetry.jsonl) and
 * a debug console (the console command “planner …” calling your IPlannerCheats). The data checks run in the bridge's
 * Validate (Python), so they need no C++.
 */
export type UnrealNames = {
  api: string
  /** Folder of the generated code, from the adapter root (Source/PlannerGame/Generated/). */
  gen: string
  project: string
  schemaType(s: IrSchema): string
  identifier(words: string[]): string
  cppString(s: string): string
  meta(s: string): string
}

const HEADER = (ir: EngineIR, what: string) => [`// Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name.replace(/\*\//g, '* /')}”: ${what}.`, '// Do not edit: the next export replaces this file.']
const comment = (s: string) => s.replace(/\*\//g, '* /')
const WORDS = ['', 'OneParam', 'TwoParams', 'ThreeParams', 'FourParams', 'FiveParams', 'SixParams', 'SevenParams', 'EightParams', 'NineParams']

type Typed = { value: string; arg: string; native: string }
/** C++ types of a parameter: by value (structs, delegates), as an argument, and in a native delegate's signature. */
function typeOf(p: IrParam, ir: EngineIR, n: UnrealNames): Typed {
  const t = p.type
  if (t.k === 'ref') {
    const s = ir.schemas.find((x) => x.id === t.schema)
    if (s && s.format === 'native') return { value: `${n.schemaType(s)}*`, arg: `${n.schemaType(s)}*`, native: `${n.schemaType(s)}*` }
    return { value: 'FName', arg: 'FName', native: 'FName' }
  }
  if (t.k === 'string') return { value: 'FString', arg: 'const FString&', native: 'const FString&' }
  const v = t.k === 'int' ? 'int32' : t.k
  return { value: v, arg: v, native: v }
}
const names = (ps: IrParam[], n: UnrealNames) => {
  const used = new Set<string>()
  return ps.map((p) => {
    let name = n.identifier(p.words) || 'Value'
    for (let i = 2; used.has(name); i++) name = `${n.identifier(p.words)}${i}`
    used.add(name)
    return name
  })
}
/** Record types the parameters use, forward-declared. */
const forward = (ps: IrParam[], ir: EngineIR, n: UnrealNames) =>
  [...new Set(ps.flatMap((p) => (p.type.k === 'ref' ? [ir.schemas.find((s) => s.id === (p.type as { schema: string }).schema)] : [])).filter((s): s is IrSchema => !!s && s.format === 'native').map((s) => `class ${n.schemaType(s)};`))].sort()

function channelDoc(c: EngineIR['channels'][number]): string {
  return [`${c.name} (${c.kindLabel || 'channel'}${c.frequency ? `, ${c.frequency.toLowerCase()}` : ''}).`, c.publishers.length ? `Published by ${c.publishers.join(', ')}.` : '', c.subscribers.length ? `Listened to by ${c.subscribers.join(', ')}.` : ''].filter(Boolean).join(' ')
}

// ---- Channels ----

export function channelFiles(ir: EngineIR, n: UnrealNames): EmittedFile[] {
  const out: EmittedFile[] = []
  const bus = ir.channels.filter((c) => c.kind === 'bus')
  if (bus.length) {
    const used = new Set<string>()
    const decls: string[] = []
    const members: string[] = []
    const defs: string[] = []
    for (const c of bus) {
      let name = n.identifier(c.words) || 'Event'
      for (let k = 2; used.has(name); k++) name = `${n.identifier(c.words)}${k}`
      used.add(name)
      const types = c.payload.slice(0, 9).map((p) => typeOf(p, ir, n).native)
      const delegate = `FPlannerOn${name}`
      decls.push(`DECLARE_MULTICAST_DELEGATE${types.length ? '_' + WORDS[types.length] : ''}(${[delegate, ...types].join(', ')});`)
      members.push(`\t/** ${comment(channelDoc(c))}${c.payload.length ? ` Payload: ${c.payload.map((p) => p.name).join(', ')}.` : ''} */`, `\tstatic ${delegate} ${name};`, '')
      defs.push(`${delegate} FPlannerGameEvents::${name};`)
    }
    members.pop()
    const all = bus.flatMap((c) => c.payload)
    out.push(
      {
        path: `${n.gen}PlannerGameEvents.h`,
        content: [
          ...HEADER(ir, 'event bus from the Architecture'),
          '#pragma once',
          '',
          '#include "CoreMinimal.h"',
          '',
          ...forward(all, ir, n),
          '',
          ...decls,
          '',
          '/**',
          ' * The Architecture’s event-bus channels as native multicast delegates:',
          ' * FPlannerGameEvents::NeedChanged.AddUObject(this, &UMyHud::OnNeedChanged), and .Broadcast(…) to raise.',
          ' * Remove your binding (RemoveAll(this)) in EndPlay.',
          ' */',
          `struct ${n.api} FPlannerGameEvents`,
          '{',
          ...members,
          '};',
          '',
        ].join('\n'),
      },
      { path: `${n.gen}PlannerGameEvents.cpp`, content: [...HEADER(ir, 'event bus from the Architecture'), '#include "PlannerGameEvents.h"', '', ...defs, ''].join('\n') },
    )
  }
  const used = new Set<string>()
  for (const c of ir.channels.filter((x) => x.kind === 'asset')) {
    let base = `${n.identifier(c.words) || 'Event'}Channel`
    for (let k = 2; used.has(base); k++) base = `${n.identifier(c.words)}${k}Channel`
    used.add(base)
    const ps = c.payload.slice(0, 9)
    const ns = names(ps, n)
    const types = ps.map((p) => typeOf(p, ir, n))
    const delegate = `FPlanner${base}Raised`
    const args = types.map((t, i) => `${t.value === 'FString' ? 'const FString&' : t.value} ${ns[i]}`).join(', ')
    out.push({
      path: `${n.gen}${base}.h`,
      content: [
        ...HEADER(ir, 'channel from the Architecture'),
        '#pragma once',
        '',
        '#include "CoreMinimal.h"',
        '#include "Engine/DataAsset.h"',
        `#include "${base}.generated.h"`,
        '',
        ...forward(ps, ir, n),
        '',
        `DECLARE_DYNAMIC_MULTICAST_DELEGATE${types.length ? '_' + WORDS[types.length] : ''}(${[delegate, ...types.flatMap((t, i) => [t.value, ns[i]])].join(', ')});`,
        '',
        `/** ${comment(channelDoc(c))} The bridge makes one asset of it under /Game/HoHPlanner/Channels; share that asset between the actors that talk. */`,
        'UCLASS(BlueprintType)',
        `class ${n.api} U${base} : public UDataAsset`,
        '{',
        '\tGENERATED_BODY()',
        '',
        'public:',
        `\tstatic constexpr const TCHAR* ChannelId = ${n.cppString(c.id)};`,
        '',
        '\tUPROPERTY(BlueprintAssignable, Category = "Planner|Channels")',
        `\t${delegate} OnRaised;`,
        '',
        `\tUFUNCTION(BlueprintCallable, Category = ${n.meta(`Planner|Channels|${c.name}`)})`,
        `\tvoid Raise(${args}) { OnRaised.Broadcast(${ns.join(', ')}); }`,
        '};',
        '',
      ].join('\n'),
    })
  }
  return out
}

// ---- Telemetry ----

export function telemetryFiles(ir: EngineIR, n: UnrealNames): EmittedFile[] {
  if (!ir.telemetry.length) return []
  const cls = `U${n.project}Telemetry`
  const file = `${n.project}Telemetry`
  const used = new Set<string>(['SetEnabled', 'FilePath'])
  const decls: string[] = []
  const defs: string[] = []
  const all: IrParam[] = []
  for (const t of ir.telemetry) {
    let m = n.identifier(t.words) || 'Event'
    for (let k = 2; used.has(m); k++) m = `${n.identifier(t.words)}${k}`
    used.add(m)
    all.push(...t.params)
    const ns = names(t.params, n)
    const types = t.params.map((p) => typeOf(p, ir, n))
    const sig = types.map((ty, i) => `${ty.arg} ${ns[i]}`).join(', ')
    const metrics = [`${t.key}.count`, ...t.params.filter((p) => p.type.k === 'int' || p.type.k === 'float').map((p) => `${t.key}.${p.words.join('_')}`)]
    decls.push(`\t/** ${comment([`${t.name}.`, t.notes, `Metrics: ${metrics.join(', ')}.`].filter(Boolean).join(' '))} */`, '\tUFUNCTION(BlueprintCallable, Category = "Planner|Telemetry")', `\tstatic void ${m}(${sig});`, '')
    const sets = t.params.map((p, i) => {
      const key = n.cppString(p.words.join('_'))
      if (p.type.k === 'ref') return types[i].value.endsWith('*') ? `\tSetText(*Values, ${key}, ${ns[i]} ? ${ns[i]}->Id.ToString() : FString());` : `\tSetText(*Values, ${key}, ${ns[i]}.ToString());`
      if (p.type.k === 'string') return `\tSetText(*Values, ${key}, ${ns[i]});`
      if (p.type.k === 'bool') return `\tValues->SetBoolField(${key}, ${ns[i]});`
      return `\tValues->SetNumberField(${key}, ${ns[i]});`
    })
    defs.push(`void ${cls}::${m}(${sig})`, '{', '\tconst TSharedRef<FJsonObject> Values = MakeShared<FJsonObject>();', ...sets, `\tWrite(${n.cppString(t.key)}, Values);`, '}', '')
  }
  decls.pop()
  const header = [
    ...HEADER(ir, 'telemetry events of the Balance plan'),
    '#pragma once',
    '',
    '#include "CoreMinimal.h"',
    '#include "Kismet/BlueprintFunctionLibrary.h"',
    `#include "${file}.generated.h"`,
    '',
    'class FJsonObject;',
    ...forward(all, ir, n),
    '',
    '/**',
    ' * Playtest telemetry from the Balance plan: one typed call per event (C++ and Blueprint), each appending a JSON line',
    ' * to Saved/hoh-telemetry.jsonl. The planner bridge adds the lines up into metrics (<key>.count and the mean of each',
    ' * number parameter) for the report. SetEnabled(false) logs nothing, e.g. in shipping builds.',
    ' */',
    'UCLASS()',
    `class ${n.api} ${cls} : public UBlueprintFunctionLibrary`,
    '{',
    '\tGENERATED_BODY()',
    '',
    'public:',
    ...decls,
    '',
    '\tUFUNCTION(BlueprintCallable, Category = "Planner|Telemetry")',
    '\tstatic void SetEnabled(bool bEnabled);',
    '',
    '\tstatic FString FilePath();',
    '',
    'private:',
    '\tstatic void Write(const FString& Key, const TSharedRef<FJsonObject>& Values);',
    '};',
    '',
  ]
  const cpp = [
    ...HEADER(ir, 'telemetry events of the Balance plan'),
    `#include "${file}.h"`,
    '#include "Dom/JsonObject.h"',
    '#include "HAL/FileManager.h"',
    '#include "Misc/App.h"',
    '#include "Misc/FileHelper.h"',
    '#include "Misc/Guid.h"',
    '#include "Misc/Paths.h"',
    '#include "Policies/CondensedJsonPrintPolicy.h"',
    '#include "Serialization/JsonSerializer.h"',
    '#include "Serialization/JsonWriter.h"',
    '',
    'namespace',
    '{',
    '\tbool GTelemetryEnabled = true;',
    '',
    '\tvoid SetText(FJsonObject& Values, const TCHAR* Key, const FString& Text)',
    '\t{',
    '\t\tif (Text.IsEmpty()) Values.SetField(Key, MakeShared<FJsonValueNull>());',
    '\t\telse Values.SetStringField(Key, Text);',
    '\t}',
    '}',
    '',
    `void ${cls}::SetEnabled(bool bEnabled)`,
    '{',
    '\tGTelemetryEnabled = bEnabled;',
    '}',
    '',
    `FString ${cls}::FilePath()`,
    '{',
    '\treturn FPaths::Combine(FPaths::ProjectSavedDir(), TEXT("hoh-telemetry.jsonl"));',
    '}',
    '',
    `void ${cls}::Write(const FString& Key, const TSharedRef<FJsonObject>& Values)`,
    '{',
    '\tif (!GTelemetryEnabled)',
    '\t{',
    '\t\treturn;',
    '\t}',
    '\tstatic const FString Session = FGuid::NewGuid().ToString(EGuidFormats::Digits);',
    '\tconst TSharedRef<FJsonObject> Line = MakeShared<FJsonObject>();',
    '\tLine->SetStringField(TEXT("event"), Key);',
    '\tLine->SetStringField(TEXT("t"), FDateTime::UtcNow().ToIso8601());',
    '\tLine->SetStringField(TEXT("session"), Session);',
    '\tLine->SetStringField(TEXT("build"), FApp::GetBuildVersion());',
    '\tfor (const TPair<FString, TSharedPtr<FJsonValue>>& Value : Values->Values)',
    '\t{',
    '\t\tLine->SetField(Value.Key, Value.Value);',
    '\t}',
    '\tFString Out;',
    '\tFJsonSerializer::Serialize(Line, TJsonWriterFactory<TCHAR, TCondensedJsonPrintPolicy<TCHAR>>::Create(&Out));',
    '\tFFileHelper::SaveStringToFile(Out + TEXT("\\n"), *FilePath(), FFileHelper::EEncodingOptions::ForceUTF8WithoutBOM, &IFileManager::Get(), FILEWRITE_Append);',
    '}',
    '',
    ...defs,
  ]
  return [
    { path: `${n.gen}${file}.h`, content: header.join('\n') },
    { path: `${n.gen}${file}.cpp`, content: cpp.join('\n') },
  ]
}

// ---- Debug console ----

const pascalCommand = (c: IrCheat) => c.words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('')

export function consoleFiles(ir: EngineIR, n: UnrealNames): EmittedFile[] {
  if (!ir.cheats.length) return []
  const params = (c: IrCheat) => c.args.flatMap((a) => (a.kind === 'time' ? ['int32 Hour', 'int32 Minute'] : [`${a.kind === 'int' ? 'int32' : 'const FString&'} ${a.name.charAt(0).toUpperCase() + a.name.slice(1)}`])).join(', ')
  const lists = new Map<string, string[]>()
  for (const c of ir.cheats) for (const a of c.args) if (a.kind === 'id' && a.values) lists.set(a.name, a.values.map((v) => v.id))
  const help = ir.cheats.map((c) => `${c.command} ${c.args.map((a) => (a.optional ? `[${a.name}]` : `<${a.name}>`)).join(' ')}`.trim() + ` — ${c.help}`)
  const header = [
    ...HEADER(ir, 'debug console'),
    '#pragma once',
    '',
    '#include "CoreMinimal.h"',
    '',
    '/** What each console command does in your game. Implement it and pass it to PlannerConsole::SetHandler at start-up. */',
    `class ${n.api} IPlannerCheats`,
    '{',
    'public:',
    '\tvirtual ~IPlannerCheats() = default;',
    ...ir.cheats.flatMap((c) => [`\t/** ${comment(`${c.command}: ${c.help}`)} */`, `\tvirtual void ${pascalCommand(c)}(${params(c)}) = 0;`]),
    '};',
    '',
    '/**',
    ' * Development console with the plan’s commands: in the game’s console (`), “planner give item.iron_sword 5”; in code,',
    ' * PlannerConsole::Run(TEXT("give item.iron_sword 5")). Commands and IDs are checked against the plan. Not in shipping builds.',
    ' */',
    'namespace PlannerConsole',
    '{',
    `\t${n.api} void SetHandler(IPlannerCheats* Handler);`,
    `\t${n.api} FString Run(const FString& Line);`,
    `\t${n.api} TArray<FString> Complete(const FString& Line);`,
    '}',
    '',
  ]
  const cases = ir.cheats.flatMap((c, ci) => {
    const required = c.args.filter((a) => !a.optional).length
    const usage = `${c.command} ${c.args.map((a) => (a.optional ? `[${a.name}]` : `<${a.name}>`)).join(' ')}`.trim()
    const out = [`\t${ci ? 'else ' : ''}if (Command == ${n.cppString(c.command)})`, '\t{', `\t\tif (Parts.Num() < ${required + 1}) return ${n.cppString(`Usage: ${usage}`)};`]
    const call: string[] = []
    c.args.forEach((a, i) => {
      const at = `Parts[${i + 1}]`
      if (a.kind === 'id') {
        out.push(`\t\tconst FString A${i} = ${a.optional ? `Parts.Num() > ${i + 1} ? ${at} : FString()` : at};`, `\t\tFString E${i};`, `\t\tif (!Known(${n.cppString(a.name)}, A${i}, E${i})) return E${i};`)
        call.push(`A${i}`)
      } else if (a.kind === 'int') {
        out.push(`\t\tint32 A${i} = 1;`, `\t\tif (Parts.Num() > ${i + 1} && !LexTryParseString(A${i}, *${at})) return ${n.cppString(`${a.name} must be a whole number.`)};`)
        call.push(`A${i}`)
      } else {
        out.push(`\t\tint32 H${i} = 0, M${i} = 0;`, `\t\tif (!TryTime(${at}, H${i}, M${i})) return ${n.cppString('Time must be HH:MM, e.g. 18:30.')};`)
        call.push(`H${i}`, `M${i}`)
      }
    })
    out.push('\t\tif (!GHandler) return NoHandler;', `\t\tGHandler->${pascalCommand(c)}(${call.join(', ')});`, '\t}')
    return out
  })
  const kinds = ir.cheats.map((c) => `\t\t\t{ ${n.cppString(c.command)}, { ${c.args.map((a) => (a.kind === 'id' ? n.cppString(a.name) : 'TEXT("")')).join(', ')} } },`)
  const cpp = [
    ...HEADER(ir, 'debug console'),
    '#include "PlannerConsole.h"',
    '#include "HAL/IConsoleManager.h"',
    '',
    'namespace',
    '{',
    '\tIPlannerCheats* GHandler = nullptr;',
    '\tconst TCHAR* NoHandler = TEXT("No handler: call PlannerConsole::SetHandler with your IPlannerCheats.");',
    '',
    '\tconst TArray<FString>& Commands()',
    '\t{',
    `\t\tstatic const TArray<FString> List = { ${help.map((h) => n.cppString(h)).join(', ')} };`,
    '\t\treturn List;',
    '\t}',
    '',
    '\tconst TMap<FString, TArray<FString>>& Values()',
    '\t{',
    '\t\tstatic const TMap<FString, TArray<FString>> Map = {',
    ...[...lists].map(([k, v]) => `\t\t\t{ ${n.cppString(k)}, { ${v.map((x) => n.cppString(x)).join(', ')} } },`),
    '\t\t};',
    '\t\treturn Map;',
    '\t}',
    '',
    '\tconst TMap<FString, TArray<FString>>& Args()',
    '\t{',
    '\t\tstatic const TMap<FString, TArray<FString>> Map = {',
    ...kinds,
    '\t\t};',
    '\t\treturn Map;',
    '\t}',
    '',
    '\tbool Known(const FString& Kind, const FString& Id, FString& Error)',
    '\t{',
    '\t\tconst TArray<FString>* Ids = Values().Find(Kind);',
    '\t\tif (Ids && Ids->Contains(Id)) return true;',
    '\t\tTArray<FString> Close;',
    '\t\tif (Ids) for (const FString& X : *Ids) if (X.Contains(Id) && Close.Num() < 3) Close.Add(X);',
    '\t\tError = FString::Printf(TEXT("No %s “%s” in the plan.%s"), *Kind, *Id, Close.Num() ? *FString::Printf(TEXT(" Did you mean %s?"), *FString::Join(Close, TEXT(", "))) : TEXT(""));',
    '\t\treturn false;',
    '\t}',
    '',
    '\tbool TryTime(const FString& Text, int32& Hour, int32& Minute)',
    '\t{',
    '\t\tFString H, M;',
    '\t\treturn Text.Split(TEXT(":"), &H, &M) && LexTryParseString(Hour, *H) && LexTryParseString(Minute, *M) && Hour >= 0 && Hour < 24 && Minute >= 0 && Minute < 60;',
    '\t}',
    '}',
    '',
    'void PlannerConsole::SetHandler(IPlannerCheats* Handler)',
    '{',
    '\tGHandler = Handler;',
    '}',
    '',
    'FString PlannerConsole::Run(const FString& Line)',
    '{',
    '\tTArray<FString> Parts;',
    '\tLine.TrimStartAndEnd().ParseIntoArrayWS(Parts);',
    '\tif (Parts.Num() == 0) return FString();',
    '\tconst FString Command = Parts[0].ToLower();',
    '\tif (Command == TEXT("help")) return FString::Join(Commands(), TEXT("\\n"));',
    ...cases,
    '\telse',
    '\t{',
    '\t\treturn FString::Printf(TEXT("Unknown command “%s”. Type help."), *Parts[0]);',
    '\t}',
    '\treturn TEXT("OK: ") + Line.TrimStartAndEnd();',
    '}',
    '',
    'TArray<FString> PlannerConsole::Complete(const FString& Line)',
    '{',
    '\tTArray<FString> Parts;',
    '\tLine.ParseIntoArray(Parts, TEXT(" "), false);',
    '\tTArray<FString> Out;',
    '\tif (Parts.Num() == 0) return Out;',
    '\tconst FString& Last = Parts.Last();',
    '\tif (Parts.Num() == 1)',
    '\t{',
    '\t\tfor (const TPair<FString, TArray<FString>>& C : Args()) if (C.Key.StartsWith(Last)) Out.Add(C.Key);',
    '\t\treturn Out;',
    '\t}',
    '\tconst TArray<FString>* Kinds = Args().Find(Parts[0]);',
    '\tconst int32 I = Parts.Num() - 2;',
    '\tconst TArray<FString>* Ids = Kinds && Kinds->IsValidIndex(I) ? Values().Find((*Kinds)[I]) : nullptr;',
    '\tif (Ids) for (const FString& Id : *Ids) if (Id.StartsWith(Last)) Out.Add(Id);',
    '\treturn Out;',
    '}',
    '',
    '#if !UE_BUILD_SHIPPING',
    'static FAutoConsoleCommand GPlannerConsoleCommand(',
    '\tTEXT("planner"),',
    '\tTEXT("Game Design Planner cheats, e.g. planner give item.iron_sword 5. planner help lists them."),',
    '\tFConsoleCommandWithArgsDelegate::CreateLambda([](const TArray<FString>& Args)',
    '\t{',
    '\t\tUE_LOG(LogTemp, Display, TEXT("%s"), *PlannerConsole::Run(FString::Join(Args, TEXT(" "))));',
    '\t}));',
    '#endif',
    '',
  ]
  return [
    { path: `${n.gen}PlannerConsole.h`, content: header.join('\n') },
    { path: `${n.gen}PlannerConsole.cpp`, content: cpp.join('\n') },
  ]
}
