/**
 * Unity output for a playable prototype's player (plans/UNITY_PLAYABLE_GAME_GENERATION_PLAN.md, phase 7), from the IR's
 * `gameplay` part: an action map with one Move stick (a 2D-vector composite of the four planned Move keys, plus the left
 * stick when the plan has a gamepad) and Interact; `PlannerGameplay` with the planned settings; and a PlayMode test that
 * walks the player with those keys through the generated asset. Uses the planner runtime package (0.10.0 or later) and,
 * for input, the Input System package. Written only when the plan chose player movement.
 */
