import type { EmittedFile } from '../adapter'
import type { EngineIR, IrSetup } from '../ir'

/**
 * Unity project set-up from Coding Standards and Architecture: .editorconfig (style and naming rules), .gitattributes
 * (Unity YAML merge, Git LFS), .gitignore, and setup.json (planned folders and one assembly per module). The bridge
 * package installs them on request (Tools ▸ Game Design Planner ▸ Set up project) and never overwrites what is there.
 */

const SEVERITY: Record<string, string> = { Blocker: 'error', Major: 'warning', Minor: 'suggestion', Nit: 'silent' }
/** Coding Standards target → .editorconfig symbol spec. Asset and file targets have no C# symbol and are left out. */
const SYMBOLS: Record<string, { kinds: string; access?: string; modifiers?: string }> = {
  Namespace: { kinds: 'namespace' },
  'Class / struct': { kinds: 'class, struct, enum, delegate' },
  Interface: { kinds: 'interface' },
  Method: { kinds: 'method, local_function' },
  Property: { kinds: 'property' },
  'Public field': { kinds: 'field', access: 'public, internal, protected_internal' },
  'Private field': { kinds: 'field', access: 'private, protected, private_protected' },
  Constant: { kinds: 'field', modifiers: 'const' },
  Event: { kinds: 'event' },
  'Parameter / local': { kinds: 'parameter, local' },
}
const CASING: Record<string, { cap: string; sep?: string }> = {
  PascalCase: { cap: 'pascal_case' },
  camelCase: { cap: 'camel_case' },
  UPPER_SNAKE: { cap: 'all_upper', sep: '_' },
  snake_case: { cap: 'all_lower', sep: '_' },
}
/** Constants first: a const field is a field too, and the first matching rule wins. */
const ORDER = ['Constant', 'Interface', 'Public field', 'Private field', 'Event', 'Property', 'Method', 'Class / struct', 'Namespace', 'Parameter / local']

export function editorconfig(setup: IrSetup): string {
  const s = setup.style
  const out = [
    '# Generated by Game Design Planner from Coding Standards (code style and naming rules). Change the rules in the planner.',
    'root = true',
    '',
    '[*]',
    'charset = utf-8',
    'insert_final_newline = true',
    'trim_trailing_whitespace = true',
    `indent_style = ${s.indent === 'tabs' ? 'tab' : 'space'}`,
    `indent_size = ${s.indentSize ?? 4}`,
    ...(s.lineLength ? [`max_line_length = ${s.lineLength}`] : []),
    '',
    '[*.{json,asmdef,yml,yaml}]',
    'indent_size = 2',
    '',
    '[*.cs]',
    ...(s.braces ? [`csharp_new_line_before_open_brace = ${s.braces === 'newline' ? 'all' : 'none'}`] : []),
  ]
  const rules = setup.naming
    .filter((r) => SYMBOLS[r.target] && CASING[r.casing])
    .sort((a, b) => ORDER.indexOf(a.target) - ORDER.indexOf(b.target))
  const used = new Set<string>()
  for (const r of rules) {
    let id = r.target.toLowerCase().replace(/[^a-z]+/g, '_').replace(/^_|_$/g, '')
    while (used.has(id)) id += '_2'
    used.add(id)
    const sym = SYMBOLS[r.target]
    const cas = CASING[r.casing]
    out.push(
      '',
      `# ${r.target}: ${r.casing}${r.prefix ? `, prefix “${r.prefix}”` : ''}${r.suffix ? `, suffix “${r.suffix}”` : ''}${r.automated ? '' : ' (reviewed by hand in the plan)'}`,
      `dotnet_naming_symbols.${id}.applicable_kinds = ${sym.kinds}`,
      ...(sym.access ? [`dotnet_naming_symbols.${id}.applicable_accessibilities = ${sym.access}`] : []),
      ...(sym.modifiers ? [`dotnet_naming_symbols.${id}.required_modifiers = ${sym.modifiers}`] : []),
      `dotnet_naming_style.${id}_style.capitalization = ${cas.cap}`,
      ...(cas.sep ? [`dotnet_naming_style.${id}_style.word_separator = ${cas.sep}`] : []),
      // A namespace prefix such as “Cinder.” is not a .editorconfig naming option; analyzers check it.
      ...(r.prefix && r.target !== 'Namespace' ? [`dotnet_naming_style.${id}_style.required_prefix = ${r.prefix}`] : []),
      ...(r.suffix ? [`dotnet_naming_style.${id}_style.required_suffix = ${r.suffix}`] : []),
      `dotnet_naming_rule.${id}.symbols = ${id}`,
      `dotnet_naming_rule.${id}.style = ${id}_style`,
      `dotnet_naming_rule.${id}.severity = ${r.automated ? SEVERITY[r.severity] ?? 'suggestion' : 'suggestion'}`,
    )
  }
  return out.join('\n') + '\n'
}

const UNITY_YAML = ['*.unity', '*.prefab', '*.asset', '*.mat', '*.anim', '*.controller', '*.overrideController', '*.physicMaterial', '*.physicsMaterial2D', '*.playable', '*.mask', '*.brush', '*.flare', '*.fontsettings', '*.guiskin', '*.giparams', '*.renderTexture', '*.spriteatlas', '*.terrainlayer', '*.mixer', '*.shadervariants', '*.preset', '*.lighting', '*.meta']

export function gitattributes(setup: IrSetup): string {
  return [
    '# Generated by Game Design Planner from Coding Standards (Git LFS patterns and the asset folders’ binary types).',
    '* text=auto',
    '*.cs diff=csharp text',
    '',
    '# Unity YAML: merge with UnityYAMLMerge (set it up as the “unityyamlmerge” merge driver in git config).',
    ...UNITY_YAML.map((p) => `${p} merge=unityyamlmerge eol=lf`),
    ...(setup.lfs.length ? ['', '# Git LFS', ...setup.lfs.map((p) => `${p} filter=lfs diff=lfs merge=lfs -text`)] : []),
  ].join('\n') + '\n'
}

const UNITY_IGNORE = ['/[Ll]ibrary/', '/[Tt]emp/', '/[Oo]bj/', '/[Bb]uild/', '/[Bb]uilds/', '/[Ll]ogs/', '/[Uu]ser[Ss]ettings/', '/[Mm]emoryCaptures/', '/[Rr]ecordings/', '.vs/', '.idea/', '.vscode/', '*.csproj', '*.unityproj', '*.sln', '*.suo', '*.user', '*.userprefs', '*.pidb', '*.booproj', '*.svd', '*.pdb', '*.mdb', '*.opendb', '*.VC.db', '*.apk', '*.aab', '*.unitypackage', 'crashlytics-build.properties', '.DS_Store', 'Thumbs.db']

export function gitignore(setup: IrSetup): string {
  const extra = setup.ignore.filter((x) => !UNITY_IGNORE.includes(x))
  return ['# Generated by Game Design Planner: Unity defaults plus the planned highlights.', ...UNITY_IGNORE, ...(extra.length ? ['', '# From the plan', ...extra] : [])].join('\n') + '\n'
}

export type SetupFolder = { path: string; purpose?: string; asmdef?: { name: string; rootNamespace: string; references: string[] } }

/** Planned folders, each module folder with an assembly that references the generated one and the modules it depends on. */
export function setupFolders(ir: EngineIR, generatedAssembly: string, identifier: (ws: string[]) => string): SetupFolder[] {
  const modules = new Map(ir.setup.modules.map((m) => [m.id, m]))
  const asmName = (id: string) => {
    const m = modules.get(id)
    return m ? m.assembly || m.words.map((w) => identifier([w])).join('.') : undefined
  }
  const withAssembly = new Set(ir.setup.folders.filter((f) => f.assembly && f.module && modules.has(f.module)).map((f) => f.module!))
  return ir.setup.folders
    .filter((f) => f.path.startsWith('Assets/'))
    .map((f) => {
      const id = f.assembly && f.module ? f.module : undefined
      const name = id ? asmName(id) : undefined
      return {
        path: f.path,
        ...(f.purpose && { purpose: f.purpose }),
        ...(id && name && { asmdef: { name, rootNamespace: name, references: [generatedAssembly, ...modules.get(id)!.dependsOn.filter((d) => withAssembly.has(d)).map((d) => asmName(d)!)] } }),
      }
    })
}

export function setupFiles(ir: EngineIR, generatedAssembly: string, identifier: (ws: string[]) => string): EmittedFile[] {
  return [
    { path: 'ProjectFiles/.editorconfig', content: editorconfig(ir.setup) },
    { path: 'ProjectFiles/.gitattributes', content: gitattributes(ir.setup) },
    { path: 'ProjectFiles/.gitignore', content: gitignore(ir.setup) },
    { path: 'ProjectFiles/setup.json', content: JSON.stringify({ generatedAssembly, folders: setupFolders(ir, generatedAssembly, identifier) }, null, 2) + '\n' },
  ]
}
