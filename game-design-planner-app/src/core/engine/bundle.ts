/** Folder every file of the zip sits in, so unpacking into a Unity Assets folder or a Godot project gives one tidy folder. */
export const BUNDLE_ROOT = 'HoHPlanner'

export type EngineBundle = { ir: EngineIR; issues: EngineIssue[]; manifest: EngineManifest; files: EmittedFile[] }

const LEVEL_ORDER = { error: 0, warning: 1, info: 2 } as const
const fileSafe = (s: string) => s.replace(/[^\w.-]/g, '_')
const json = (v: unknown) => JSON.stringify(v, null, 2) + '\n'

function csvCell(v: unknown): string {
  const s = v === null || v === undefined ? '' : Array.isArray(v) ? (v.every((x) => typeof x !== 'object') ? v.join(';') : JSON.stringify(v)) : String(v)
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
}
const csv = (rows: unknown[][]) => rows.map((r) => r.map(csvCell).join(',')).join('\n') + '\n'

function schemaFolders(ir: EngineIR): Map<string, string> {
  const names = uniqueNames(ir.schemas.map((s) => pascal(s.words) || 'Schema'))
  return new Map(ir.schemas.map((s, i) => [s.id, names[i]]))
}

function dataFiles(ir: EngineIR, folders: Map<string, string>): { files: EmittedFile[]; paths: Map<string, string> } {
  const files: EmittedFile[] = []
  const paths = new Map<string, string>()
  for (const s of ir.schemas) {
    const recs = ir.records.filter((r) => r.schema === s.id)
    const folder = `Data/${folders.get(s.id)}`
    if (s.format === 'csv') {
      paths.set(s.id, `${folder}.csv`)
      const head = ['id', 'plannerId', ...s.fields.map((f) => f.name)]
      files.push({ path: `${folder}.csv`, content: csv([head, ...recs.map((r) => [r.key, r.plannerId, ...s.fields.map((f) => r.values[f.name])])]) })
    } else {
      paths.set(s.id, `${folder}/`)
      for (const r of recs) {
        const { id, ...rest } = r.values
        files.push({ path: `${folder}/${fileSafe(r.key)}.json`, content: json({ id, plannerId: r.plannerId, ...rest }) })
      }
    }
  }
  return { files, paths }
}

function mapFiles(p: Project): EmittedFile[] {
  const locations = (p.documents[WORLD_DOC]?.data.locations ?? []) as Entity[]
  return locations.filter((l) => mapOf(l)).map((l) => ({ path: `Maps/${fileSafe(String(l.id))}.json`, content: json(locationJson(l, mapOf(l)!)) }))
}

