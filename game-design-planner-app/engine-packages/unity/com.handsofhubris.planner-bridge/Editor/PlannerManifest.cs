using System.Collections.Generic;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace HoHPlanner.Bridge.Editor
{
    /// <summary>One schema as the manifest lists it.</summary>
    public sealed class ManifestSchema
    {
        public string Id;
        public string Name;
        /// <summary>“native” (a ScriptableObject per record), “json” or “csv”.</summary>
        public string Format;
        public string IdPrefix;
        public int Version;
        public int Records;
        /// <summary>Folder (native, json) or file (csv) holding the records, relative to the bundle root.</summary>
        public string Data;
    }

    /// <summary>hoh-engine.json: what the bundle holds. The contract is Tests/Editor/Fixtures/hoh-engine.schema.json (generated by the planner).</summary>
    public sealed class PlannerManifest
    {
        public const string Format = "hoh-engine";
        public const int SupportedVersion = 1;

        public int Version;
        public string Engine;
        /// <summary>0 = the planner has no code generator for this engine; the bundle holds data only.</summary>
        public int AdapterVersion;
        public string ProjectName;
        public string ExportedAt;
        public List<ManifestSchema> Schemas = new List<ManifestSchema>();
        public Dictionary<string, string> FileHashes = new Dictionary<string, string>();

        public bool HasUnityCode => Engine == "unity" && AdapterVersion > 0;

        /// <summary>Reads and checks a manifest. Untrusted text: throws <see cref="PlannerImportException"/> with a readable reason.</summary>
        public static PlannerManifest Parse(string text)
        {
            JObject o;
            try
            {
                o = JObject.Parse(text);
            }
            catch (JsonException e)
            {
                throw new PlannerImportException($"hoh-engine.json is not valid JSON: {e.Message}");
            }
            if ((string)o["format"] != Format) throw new PlannerImportException("hoh-engine.json is not a planner engine manifest (format is not “hoh-engine”).");
            var v = o["v"]?.Type == JTokenType.Integer ? (int)o["v"] : 0;
            if (v != SupportedVersion) throw new PlannerImportException($"This bundle uses format version {v}; this package reads version {SupportedVersion}. Update the planner bridge package (or the planner).");
            var engine = o["engine"] as JObject ?? throw new PlannerImportException("hoh-engine.json has no engine.");
            var m = new PlannerManifest
            {
                Version = v,
                Engine = (string)engine["id"],
                AdapterVersion = engine["adapterVersion"]?.Type == JTokenType.Integer ? (int)engine["adapterVersion"] : 0,
                ProjectName = (string)o["project"]?["name"] ?? "",
                ExportedAt = (string)o["exportedAt"] ?? "",
            };
            if (!(o["schemas"] is JArray schemas)) throw new PlannerImportException("hoh-engine.json has no schema list.");
            foreach (var s in schemas)
            {
                var data = (string)s["data"] ?? "";
                if (data.Length > 0 && !PlannerBundle.IsSafeRelative(data.TrimEnd('/'))) throw new PlannerImportException($"Unsafe data path in hoh-engine.json: {data}");
                m.Schemas.Add(new ManifestSchema
                {
                    Id = (string)s["id"] ?? throw new PlannerImportException("A schema in hoh-engine.json has no id."),
                    Name = (string)s["name"] ?? "",
                    Format = (string)s["format"] ?? "json",
                    IdPrefix = (string)s["idPrefix"] ?? "",
                    Version = s["version"]?.Type == JTokenType.Integer ? (int)s["version"] : 1,
                    Records = s["records"]?.Type == JTokenType.Integer ? (int)s["records"] : 0,
                    Data = data,
                });
            }
            if (o["files"] is JArray files)
                foreach (var f in files)
                {
                    var path = (string)f["path"];
                    if (path != null) m.FileHashes[path] = (string)f["hash"] ?? "";
                }
            return m;
        }
    }
}
