export function stateMachineFiles(ir: EngineIR, n: GodotNames): EmittedFile[] {
  if (!ir.stateMachines.length) return []
  const base = `${n.project}StateMachine`
  const runtime = [
    ...HEADER(ir, 'state machine runtime'),
    `class_name ${base}`,
    'extends RefCounted',
    '## A state machine that only allows the planned transitions: go(to) moves when the plan has that transition',
    '## (else returns false and stays), changed tells listeners, ended is true in an end state.',
    '',
    'signal changed(from: int, to: int)',
    '',
    'var current: int',
    'var _transitions: Array',
    'var _ends: Array',
    '',
    '',
    'func _init(start: int, transitions: Array, ends: Array) -> void:',
    '\tcurrent = start',
    '\t_transitions = transitions',
    '\t_ends = ends',
    '',
    '',
    'func ended() -> bool:',
    '\treturn current in _ends',
    '',
    '',
    '## The planned transitions from the current state, each [from, to, kind, cause].',
    'func next() -> Array:',
    '\treturn _transitions.filter(func(t): return t[0] == current)',
    '',
    '',
    'func can_go(to: int) -> bool:',
    '\treturn next().any(func(t): return t[1] == to)',
    '',
    '',
    'func go(to: int) -> bool:',
    '\tif not can_go(to):',
    '\t\treturn false',
    '\tvar from := current',
    '\tcurrent = to',
    '\tchanged.emit(from, to)',
    '\treturn true',
    '',
  ]
  const used = new Set<string>()
  const files: EmittedFile[] = [{ path: `${GEN}StateMachines/${n.fileOf(base)}.gd`, content: runtime.join('\n') }]
  for (const m of ir.stateMachines) {
    let cls = `${n.identifier(m.words, 'type')}States`
    for (let i = 2; used.has(cls); i++) cls = `${n.identifier(m.words, 'type')}${i}States`
    used.add(cls)
    files.push({ path: `${GEN}StateMachines/${n.fileOf(cls)}.gd`, content: machine(m, ir, n, cls, base) })
  }
  return files
}

function machine(m: IrStateMachine, ir: EngineIR, n: GodotNames, cls: string, base: string): string {
  const used = new Set<string>()
  const names = new Map(
    m.states.map((s) => {
      let id = n.identifier(s.words, 'constant')
      for (let i = 2; used.has(id); i++) id = `${n.identifier(s.words, 'constant')}_${i}`
      used.add(id)
      return [s.id, id]
    }),
  )
  const starts = m.states.filter((s) => s.kind === 'start')
  const first = starts[0] ?? m.states[0]
  return [
    ...HEADER(ir, `state machine ${m.name}`),
    `class_name ${cls}`,
    'extends RefCounted',
    ...doc(`${m.name}: the states and transitions drawn in the planner. create() gives a machine that only allows them.`),
    '',
    `enum State { ${m.states.map((s) => names.get(s.id)).join(', ')} }`,
    `const STARTS := [${starts.map((s) => `State.${names.get(s.id)}`).join(', ')}]`,
    `const ENDS := [${m.states.filter((s) => s.kind === 'end').map((s) => `State.${names.get(s.id)}`).join(', ')}]`,
    '## [from, to, kind, cause]',
    'const TRANSITIONS := [',
    ...m.transitions.map((t) => `\t[State.${names.get(t.from)}, State.${names.get(t.to)}, ${n.gdString(t.label || t.kind)}, ${n.gdString(t.cause ?? '')}],`),
    ']',
    '',
    '',
    `static func create(start: State = State.${names.get(first.id)}) -> ${base}:`,
    `\treturn ${base}.new(start, TRANSITIONS, ENDS)`,
    '',
  ].join('\n')
}

