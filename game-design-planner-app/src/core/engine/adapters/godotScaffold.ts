export function screenFiles(ir: EngineIR, n: GodotNames): EmittedFile[] {
  const screens = ir.ui.screens
  if (!screens.length) return []
  const cls = `${n.project}Screens`
  const ids = new Map<string, string>()
  const used = new Set<string>()
  for (const s of screens) {
    let id = n.identifier(s.words, 'constant')
    for (let i = 2; used.has(id); i++) id = `${n.identifier(s.words, 'constant')}_${i}`
    used.add(id)
    ids.set(s.id, id)
  }
  const entry = screens.find((s) => s.entry) ?? screens[0]
  const r = (v: number) => Math.round(v * 10000) / 10000
  const elements = (sid: string) =>
    screens
      .find((s) => s.id === sid)!
      .elements.map((e) => {
        const parts = [`"kind": ${n.gdString(e.kind)}`, `"rect": [${r(e.x / ir.ui.width)}, ${r(e.y / ir.ui.height)}, ${r(e.w / ir.ui.width)}, ${r(e.h / ir.ui.height)}]`]
        if (e.text) parts.push(`"text": ${n.gdString(e.text)}`)
        if (e.bind) parts.push(`"bind": ${n.gdString(`${e.bind.source}${e.bind.id ? `/${e.bind.id}` : ''}`)}`)
        if (e.opens && ids.has(e.opens)) parts.push(`"opens": Screen.${ids.get(e.opens)}`)
        return `\t\t\t{ ${parts.join(', ')} },`
      })
  const links = ir.ui.links.filter((l) => ids.has(l.from) && ids.has(l.to))
  const lines = [
    ...HEADER(ir, 'screens and their flow'),
    `class_name ${cls}`,
    'extends RefCounted',
    '## The planned screens (UI/UX › Screens) with their layout in fractions of the screen, and the planned Screen flow.',
    '## build(id) makes a Control of a screen; planner_screen_router.gd shows them and follows the flow.',
    '',
    `enum Screen { ${[...ids.values()].join(', ')} }`,
    `const ENTRY := Screen.${ids.get(entry.id)}`,
    '',
    'const SCREENS := {',
    ...screens.flatMap((s) => [`\tScreen.${ids.get(s.id)}: {`, `\t\t"name": ${n.gdString(s.name)},`, `\t\t"kind": ${n.gdString(s.kind)},`, '\t\t"elements": [', ...elements(s.id), '\t\t],', '\t},']),
    '}',
    '',
    '## [from, to, kind] as drawn in Screen flow, plus buttons that open a screen.',
    'const LINKS := [',
    ...links.map((l) => `\t[Screen.${ids.get(l.from)}, Screen.${ids.get(l.to)}, ${n.gdString(l.kind)}],`),
    ']',
    '',
    '',
    '## Whether the plan has a way from one screen to the other (any kind of link, or back the way it came).',
    'static func can_go(from: Screen, to: Screen) -> bool:',
    '\tif from == to:',
    '\t\treturn true',
    '\tfor l in LINKS:',
    '\t\tif (l[0] == from and l[1] == to) or (l[0] == to and l[1] == from):',
    '\t\t\treturn true',
    '\treturn false',
    '',
    '',
    '## A Control with the screen’s planned elements; buttons that open a screen carry meta "opens", bound elements "bind".',
    'static func build(id: Screen) -> Control:',
    '\tvar data: Dictionary = SCREENS[id]',
    '\tvar root := Control.new()',
    '\troot.name = str(data["name"]).validate_node_name()',
    '\troot.set_anchors_preset(Control.PRESET_FULL_RECT)',
    '\tfor e in data["elements"]:',
    '\t\tvar c := _element(e)',
    '\t\tvar rect: Array = e["rect"]',
    '\t\tc.anchor_left = rect[0]',
    '\t\tc.anchor_top = rect[1]',
    '\t\tc.anchor_right = rect[0] + rect[2]',
    '\t\tc.anchor_bottom = rect[1] + rect[3]',
    '\t\tif e.has("opens"):',
    '\t\t\tc.set_meta("opens", e["opens"])',
    '\t\tif e.has("bind"):',
    '\t\t\tc.set_meta("bind", e["bind"])',
    '\t\troot.add_child(c)',
    '\treturn root',
    '',
    '',
    'static func _element(e: Dictionary) -> Control:',
    '\tvar text := str(e.get("text", ""))',
    '\tmatch str(e["kind"]):',
    '\t\t"heading", "label", "text":',
    '\t\t\tvar l := Label.new()',
    '\t\t\tl.text = text',
    '\t\t\tl.horizontal_alignment = HORIZONTAL_ALIGNMENT_CENTER if e["kind"] == "heading" else HORIZONTAL_ALIGNMENT_LEFT',
    '\t\t\treturn l',
    '\t\t"button", "iconButton":',
    '\t\t\tvar b := Button.new()',
    '\t\t\tb.text = text',
    '\t\t\treturn b',
    '\t\t"statBar":',
    '\t\t\tvar p := ProgressBar.new()',
    '\t\t\tp.value = 50',
    '\t\t\treturn p',
    '\t\t"slider":',
    '\t\t\treturn HSlider.new()',
    '\t\t"checkbox":',
    '\t\t\tvar t := CheckBox.new()',
    '\t\t\tt.text = text',
    '\t\t\treturn t',
    '\t\t"dropdown":',
    '\t\t\treturn OptionButton.new()',
    '\tvar panel := PanelContainer.new()',
    '\tif text != "":',
    '\t\tvar inner := Label.new()',
    '\t\tinner.text = text',
    '\t\tpanel.add_child(inner)',
    '\treturn panel',
    '',
  ]
  const router = [
    ...HEADER(ir, 'screen router'),
    'class_name PlannerScreenRouter',
    'extends CanvasLayer',
    `## Shows the planned screens (${cls}) and follows the planned flow: starts on the entry screen, a button that opens`,
    '## a screen opens it, back() returns. Opening a screen the plan has no link to still works but warns, so the plan',
    '## and the game do not drift apart. Add it to your main scene (or as an autoload).',
    '',
    'signal changed(from: int, to: int)',
    '',
    `var current: int = ${cls}.ENTRY`,
    'var _history: Array[int] = []',
    'var _shown: Control',
    '',
    '',
    'func _ready() -> void:',
    '\t_show(current, false)',
    '',
    '',
    'func open(id: int) -> void:',
    `\tif not ${cls}.can_go(current, id):`,
    `\t\tpush_warning("Screen flow: %s → %s is not in the plan." % [${cls}.SCREENS[current]["name"], ${cls}.SCREENS[id]["name"]])`,
    '\t_show(id, true)',
    '',
    '',
    'func back() -> bool:',
    '\tif _history.is_empty():',
    '\t\treturn false',
    '\t_show(_history.pop_back(), false)',
    '\treturn true',
    '',
    '',
    'func _show(id: int, remember: bool) -> void:',
    '\tif remember:',
    '\t\t_history.append(current)',
    '\tvar from := current',
    '\tcurrent = id',
    '\tif _shown != null:',
    '\t\t_shown.queue_free()',
    `\t_shown = ${cls}.build(id)`,
    '\tadd_child(_shown)',
    '\tfor c in _shown.get_children():',
    '\t\tif c is BaseButton and c.has_meta("opens"):',
    '\t\t\tc.pressed.connect(open.bind(int(c.get_meta("opens"))))',
    '\tchanged.emit(from, id)',
    '',
  ]
  return [
    { path: `${GEN}${n.fileOf(cls)}.gd`, content: lines.join('\n') },
    { path: `${GEN}planner_screen_router.gd`, content: router.join('\n') },
  ]
}

