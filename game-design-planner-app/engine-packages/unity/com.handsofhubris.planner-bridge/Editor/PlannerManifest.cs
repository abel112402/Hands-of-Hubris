using System.Collections.Generic;
using System.Linq;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace HoHPlanner.Bridge.Editor
{
    /// <summary>One schema as the manifest lists it.</summary>
    public sealed class ManifestSchema
    {
        public string Id;
        public string Name;
        /// <summary>“native” (a ScriptableObject per record), “json” or “csv”.</summary>
        public string Format;
        public string IdPrefix;
        public int Version;
        public int Records;
        /// <summary>Folder (native, json) or file (csv) holding the records, relative to the bundle root.</summary>
        public string Data;
        /// <summary>The planned load group (Data-driven Design › Loading and Addressables), or null.</summary>
        public ManifestLoad Load;
    }

    public sealed class ManifestLoad
    {
        public string Group;
        public string Strategy;
        public string Label;
    }

    /// <summary>hoh-engine.json: what the bundle holds. The contract is Tests/Editor/Fixtures/hoh-engine.schema.json (generated by the planner).</summary>
    public sealed class PlannerManifest
    {
        public const string Format = "hoh-engine";
        public const int SupportedVersion = 1;

        public int Version;
        public string Engine;
        /// <summary>0 = the planner has no code generator for this engine; the bundle holds data only.</summary>
        public int AdapterVersion;
        public string ProjectName;
        public string ExportedAt;
        public List<ManifestSchema> Schemas = new List<ManifestSchema>();
        public Dictionary<string, string> FileHashes = new Dictionary<string, string>();

        public bool HasUnityCode => Engine == "unity" && AdapterVersion > 0;

        public const string RuntimePackageName = "com.handsofhubris.planner-runtime";
        /// <summary>The planner runtime package the export needs (a plan with a playable prototype), or null.</summary>
        public string RuntimePackage;
        public string RuntimeVersion;

        /// <summary>Why this export cannot go into a project whose runtime package is <paramref name="installed"/> (null = not installed); null when it can.</summary>
        public string RuntimeProblem(string installed)
        {
            if (RuntimePackage == null) return null;
            if (RuntimePackage != RuntimePackageName) return $"The export needs the package {RuntimePackage}, which this bridge does not know. Update the planner bridge package.";
            if (installed == null) return $"This plan asks for a playable prototype: install {RuntimePackageName} {RuntimeVersion} or later (Package Manager › Add package from git URL / disk), then import again.";
            if (CompareVersions(installed, RuntimeVersion) < 0) return $"This export needs {RuntimePackageName} {RuntimeVersion} or later; the project has {installed}. Update the package, then import again.";
            return null;
        }

        /// <summary>The installed runtime package's version, or null.</summary>
        public static string InstalledRuntimeVersion() => UnityEditor.PackageManager.PackageInfo.FindForAssetPath($"Packages/{RuntimePackageName}/package.json")?.version;

        /// <summary>Compares “major.minor.patch” numerically; a pre-release suffix is ignored, missing parts count as 0.</summary>
        public static int CompareVersions(string a, string b)
        {
            int[] Parts(string v) => (v ?? "").Split('-')[0].Split('.').Select(x => int.TryParse(x, out var n) ? n : 0).Concat(new[] { 0, 0, 0 }).Take(3).ToArray();
            var x1 = Parts(a);
            var y1 = Parts(b);
            for (var i = 0; i < 3; i++)
                if (x1[i] != y1[i]) return x1[i].CompareTo(y1[i]);
            return 0;
        }

        /// <summary>Throws when the export needs a runtime package this project does not have.</summary>
        public void RequireRuntime()
        {
            var problem = RuntimeProblem(InstalledRuntimeVersion());
            if (problem != null) throw new PlannerImportException(problem);
        }

        /// <summary>Reads and checks a manifest. Untrusted text: throws <see cref="PlannerImportException"/> with a readable reason.</summary>
        public static PlannerManifest Parse(string text)
        {
            JObject o;
            try
            {
                o = JObject.Parse(text);
            }
            catch (JsonException e)
            {
                throw new PlannerImportException($"hoh-engine.json is not valid JSON: {e.Message}");
            }
            if ((string)o["format"] != Format) throw new PlannerImportException("hoh-engine.json is not a planner engine manifest (format is not “hoh-engine”).");
            var v = o["v"]?.Type == JTokenType.Integer ? (int)o["v"] : 0;
            if (v != SupportedVersion) throw new PlannerImportException($"This bundle uses format version {v}; this package reads version {SupportedVersion}. Update the planner bridge package (or the planner).");
            var engine = o["engine"] as JObject ?? throw new PlannerImportException("hoh-engine.json has no engine.");
            var m = new PlannerManifest
            {
                Version = v,
                Engine = (string)engine["id"],
                AdapterVersion = engine["adapterVersion"]?.Type == JTokenType.Integer ? (int)engine["adapterVersion"] : 0,
                ProjectName = (string)o["project"]?["name"] ?? "",
                ExportedAt = (string)o["exportedAt"] ?? "",
            };
            if (!(o["schemas"] is JArray schemas)) throw new PlannerImportException("hoh-engine.json has no schema list.");
            foreach (var s in schemas)
            {
                var data = (string)s["data"] ?? "";
                if (data.Length > 0 && !PlannerBundle.IsSafeRelative(data.TrimEnd('/'))) throw new PlannerImportException($"Unsafe data path in hoh-engine.json: {data}");
                m.Schemas.Add(new ManifestSchema
                {
                    Id = (string)s["id"] ?? throw new PlannerImportException("A schema in hoh-engine.json has no id."),
                    Name = (string)s["name"] ?? "",
                    Format = (string)s["format"] ?? "json",
                    IdPrefix = (string)s["idPrefix"] ?? "",
                    Version = s["version"]?.Type == JTokenType.Integer ? (int)s["version"] : 1,
                    Records = s["records"]?.Type == JTokenType.Integer ? (int)s["records"] : 0,
                    Data = data,
                    Load = s["load"] is JObject load && !string.IsNullOrWhiteSpace((string)load["group"])
                        ? new ManifestLoad { Group = ((string)load["group"]).Trim(), Strategy = (string)load["strategy"] ?? "", Label = string.IsNullOrWhiteSpace((string)load["label"]) ? null : ((string)load["label"]).Trim() }
                        : null,
                });
            }
            if (o["files"] is JArray files)
                foreach (var f in files)
                {
                    var path = (string)f["path"];
                    if (path != null) m.FileHashes[path] = (string)f["hash"] ?? "";
                }
            if (o["requires"]?["runtime"] is JObject rt)
            {
                m.RuntimePackage = (string)rt["package"] ?? throw new PlannerImportException("hoh-engine.json names a runtime without a package.");
                m.RuntimeVersion = (string)rt["version"] ?? "0.0.0";
            }
            return m;
        }
    }
}
