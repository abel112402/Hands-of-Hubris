/**
 * Unity output for the content ideas (plans/UNITY_INTEGRATION_PLAN.md § 7): the quest graph with a quest log that only
 * follows the plan and an EditMode test that every quest and ending can be reached (I7), the save system with its
 * version, slots, keys and migrations (I9), and the planned scenes by roadmap phase, which the bridge puts into the
 * Build Settings (I19).
 */

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const HEADER = (ir: EngineIR, what: string) => ['// <auto-generated>', `//   Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name}”: ${what}.`, '//   Do not edit: the next import overwrites this file.', '// </auto-generated>']
const indent = (lines: string[], n = 4) => lines.map((l) => (l ? ' '.repeat(n) + l : l))
const wrap = (ir: EngineIR, ns: string, what: string, usings: string[], body: string[]) => [...HEADER(ir, what), ...usings.map((u) => `using ${u};`), '', `namespace ${ns}`, '{', ...indent(body), '}', ''].join('\n')

/** Unique C# member names for a list of named things. */
function members<T extends { words: string[] }>(items: T[], n: UnityNames, fallback: string): string[] {
  const used = new Set<string>()
  return items.map((x) => {
    const base = n.identifier(x.words).replace(/^@/, '') || fallback
    let m = base
    for (let k = 2; used.has(m); k++) m = `${base}${k}`
    used.add(m)
    return m
  })
}

