import { describe, expect, it } from 'vitest'
import { deserializeProject } from '../src/core/persistence/serialize'
import { godot, KEEP_IMPORT } from '../src/core/engine/adapters/godot'
import { buildIR } from '../src/core/engine/ir'
import { buildBundle } from '../src/core/engine/bundle'
import { exportFolderIn, folderState, writeExport } from '../src/core/engine/folder'
import { evaluate as evalFormula } from '../src/core/formula'
import { MemoryFolder } from './memoryFolder'

const fs: { readFileSync: (path: string, enc: string) => string } = await import('node:fs' as string)
const cinderholm = () => deserializeProject(fs.readFileSync('examples/cinderholm.hohplan.json', 'utf8')).project

describe('Godot adapter output', () => {
  const { ir } = buildIR(cinderholm())
  const files = new Map(godot.emit(ir).map((f) => [f.path, f.content]))
  const get = (name: string) => files.get(`Scripts/Generated/${name}`)!

  it('writes a Resource for native schemas and record classes with from_dict for JSON and CSV', () => {
    const item = get('item_definition.gd')
    expect(item).toMatch(/^# <auto-generated>/)
    expect(item).toContain('class_name ItemDefinition\nextends Resource')
    expect(item).toContain('const SCHEMA_ID := "')
    expect(item).toContain('"stackSize": "stack_size"')
    expect(item).toContain('@export var id: String\n@export_storage var planner_id: String')
    expect(item).toContain('@export var icon: Texture2D')
    expect(item).toContain('@export var rarity: CinderholmExampleEnums.Rarity')
    expect(item).toContain('@export var tags: Array[String]')
    const building = get('building_definition.gd')
    expect(building).toContain('@export var build_cost: Array[ItemDefinition]')
    expect(building).toContain('@export var footprint: Vector2')
    const recipe = get('recipe_record.gd')
    expect(recipe).toContain('class_name RecipeRecord\nextends RefCounted')
    expect(recipe).toContain('static func from_dict(d: Dictionary) -> RecipeRecord:')
    expect(recipe).toContain('\tr.inputs.assign(CinderholmExampleValues.to_list(d.get("inputs")))')
    expect(recipe).toContain('\tr.seconds = CinderholmExampleValues.to_float(d.get("seconds"))')
    expect(get('quest_record.gd')).toContain('Translation key: show it with tr().')
    // GDScript has no tabs-or-spaces choice inside one file: the generated code indents with tabs only.
    for (const [path, text] of files) if (path.endsWith('.gd')) expect(text, path).not.toMatch(/^ +\S/m)
  })

  it('writes enums with planner IDs, never named like a Godot class', () => {
    const enums = get('cinderholm_example_enums.gd')
    expect(enums).toContain('enum ItemType { BUILDING_ITEM, RESOURCE_ITEM,')
    expect(enums).toContain('const RARITY_IDS := { "common": Rarity.COMMON,')
    // The “Resources” catalog would shadow Godot's Resource class.
    expect(enums).toContain('enum ResourceKind { WOOD,')
    expect(enums).toContain('const RESOURCE_KIND_IDS := {')
    expect(enums).not.toMatch(/enum Resource \{/)
    expect(get('cinderholm_example_ids.gd')).toMatch(/class Item:\n(\tconst \w+ := "[^"]+"\n)*\tconst IRON_SWORD := "item\.iron_sword"/)
  })

  it('writes formulas that compute what the planner computes', () => {
    const text = get('cinderholm_example_formulas.gd')
    expect(text).toContain('static func health_regen_per_second(base: float, level: float, per_level: float) -> float:\n\treturn base + level * per_level')
    expect(text).toContain('base_hp * pow(1.6, stage)')
    expect(text).toContain('minf(qty, 20.0)')
    // Evaluate each generated body as JavaScript with Godot's functions, and compare with the planner.
    const godotFns = { minf: Math.min, maxf: Math.max, min: Math.min, max: Math.max, pow: Math.pow, sqrt: Math.sqrt, absf: Math.abs, floorf: Math.floor, ceilf: Math.ceil, log: Math.log, float: Number }
    for (const f of ir.formulas.filter((x) => x.ast && Object.keys(x.sample).length)) {
      const m = new RegExp(`static func \\w+\\(([^)]*)\\) -> float:\\n\\treturn (.+)\\n`).exec(text.slice(text.indexOf(`Planner: ${f.expr}.`)))
      expect(m, f.name).toBeTruthy()
      const params = m![1] ? m![1].split(', ').map((p) => p.split(':')[0]) : []
      const fn = new Function(...Object.keys(godotFns), ...params, `return ${m![2]}`)
      const got = fn(...Object.values(godotFns), ...f.params.map((p) => f.sample[p] ?? 0))
      expect(got, f.name).toBeCloseTo(evalFormula(f.expr, f.sample), 6)
    }
  })

  it('rounds halves the way the planner does', () => {
    const p = cinderholm()
    const { ir: one } = buildIR(p)
    one.formulas = [{ id: 'r', name: 'Round it', words: ['round', 'it'], where: 'test', expr: 'round(x)', params: ['x'], sample: { x: -2.5 }, ast: { k: 'call', fn: 'round', args: [{ k: 'var', name: 'x' }] } }]
    const text = godot.emit(one).find((f) => f.path.endsWith('_formulas.gd'))!.content
    expect(text).toContain('return floorf(x + 0.5)')
    expect(Math.floor(-2.5 + 0.5)).toBe(evalFormula('round(x)', { x: -2.5 }))
  })

  it('writes each diagram class as a generated base and your file that extends it', () => {
    const base = files.get('Scripts/Generated/Classes/health_base.gd')!
    expect(base).toContain('class_name HealthBase\nextends Node')
    expect(base).toContain('@export var regen_per_second: float')
    expect(base).toContain('## Implements IDamageable.')
    expect(base).toContain('func take_damage(amount: float) -> float:\n\tpush_error("Health.take_damage() is not written yet.")\n\treturn 0.0')
    const own = files.get('Scripts/Classes/gameplay_player/health.gd')!
    expect(own).toContain('class_name Health\nextends HealthBase')
    expect(own).toContain('func take_damage(amount: float) -> float:\n\treturn 0.0 # TODO')
    expect(files.get('Scripts/Generated/Classes/i_damageable.gd')).toContain('const METHODS: Array[StringName] = [&"take_damage"]')
    expect(files.get('Scripts/Generated/Classes/need_changed_event_base.gd')).toContain('signal raised(npc_id: String, need: String, amount: float)')
    // Static methods live only in your file: GDScript cannot override them.
    expect(files.get('Scripts/Generated/Classes/save_service_base.gd')).toContain('static var slot_count: int')
    expect(files.get('Scripts/Generated/Classes/save_service_base.gd')).not.toContain('func save(')
    expect(files.get('Scripts/Classes/persistence_save/save_service.gd')).toContain('static func save(slot: int) -> void:\n\tpass # TODO')
    expect(files.get('Scripts/Generated/Classes/npc_mood.gd')).toContain('enum Value { CONTENT, RESTLESS, ANGRY }')
    const index = JSON.parse(files.get('Scripts/Generated/classes.json')!)
    expect(index.find((c: { name: string }) => c.name === 'Health')).toMatchObject({ generated: 'Godot/Scripts/Generated/Classes/health_base.gd', own: 'Godot/Scripts/Classes/gameplay_player/health.gd', methods: ['take_damage', 'die'] })
    expect(index.find((c: { name: string }) => c.name === 'IDamageable').own).toBeNull()
  })

  it('declares every global class once and reports clashes', () => {
    const names = [...files.values()].flatMap((t) => [...t.matchAll(/^class_name (\w+)$/gm)].map((m) => m[1]))
    expect(new Set(names).size).toBe(names.length)
    const p = cinderholm()
    p.documents['technical.architecture'].data.classes.push({ id: 'x1', name: 'Node', kind: 'component' }, { id: 'x2', name: 'Health', kind: 'class' })
    const issues = godot.checks(buildIR(p).ir)
    expect(issues.some((i) => i.code === 'godot.typeName' && /Node is a Godot class/.test(i.message))).toBe(true)
    expect(issues.some((i) => i.code === 'godot.duplicate' && /global class Health/.test(i.message))).toBe(true)
  })

  it('writes project files from Coding Standards', () => {
    expect(files.get('ProjectFiles/.gitignore')).toMatch(/^\.godot\/$/m)
    expect(files.get('ProjectFiles/.editorconfig')).toContain('[*.gd]')
    const setup = JSON.parse(files.get('ProjectFiles/setup.json')!)
    expect(setup.folders.length).toBeGreaterThan(0)
    expect(setup.folders.every((f: { path: string }) => f.path.startsWith('res://') && !f.path.startsWith('res://Assets'))).toBe(true)
  })

  it('keeps the generated GDScript stable', () => {
    expect(get('item_definition.gd')).toMatchSnapshot()
    expect(get('recipe_record.gd')).toMatchSnapshot()
    expect(files.get('Scripts/Generated/Classes/health_base.gd')).toMatchSnapshot()
  })
})

describe('Godot bundle and linked folder', () => {
  it('keeps record CSVs from being imported as translations', () => {
    const b = buildBundle(cinderholm(), 'godot', 'T')
    expect(b.manifest.engine).toEqual({ id: 'godot', adapterVersion: godot.version })
    const csvs = b.files.filter((f) => f.path.startsWith('Data/') && f.path.endsWith('.csv'))
    expect(csvs.length).toBeGreaterThan(0)
    for (const c of csvs) expect(b.files.find((f) => f.path === `${c.path}.import`)?.content).toBe(KEEP_IMPORT)
    expect(b.files.some((f) => f.path === 'Localization/strings.csv.import')).toBe(false)
    expect(b.manifest.files.some((f) => f.path.endsWith('.csv.import'))).toBe(true)
    expect(b.files.find((f) => f.path === 'README.md')!.content).toContain('## Godot')
  })

  it('writes into res://HoHPlanner of a Godot project and leaves what Godot made alone', async () => {
    const root = new MemoryFolder('MyGame')
    root.put('project.godot', 'config_version=5')
    expect(await folderState(root)).toMatchObject({ godotProject: true, unityProject: false })
    const { folder, path } = await exportFolderIn(root)
    expect(path).toBe('HoHPlanner')
    const dir = folder as MemoryFolder
    const files = buildBundle(cinderholm(), 'godot', 'T').files
    const first = await writeExport(dir, files)
    expect(first.codeChanged).toBe(true)
    // What Godot adds after its import.
    dir.put('Godot/Scripts/Generated/item_definition.gd.uid', 'uid://abc')
    dir.put('Localization/strings.csv.import', '[remap]')
    dir.put('Localization/strings.en.translation', 'binary')
    dir.put('Godot/Scripts/Generated/old_definition.gd', '# old')
    dir.put('Godot/Scripts/Generated/old_definition.gd.uid', 'uid://old')
    dir.put('Godot/Scripts/Classes/gameplay_player/health.gd', '# mine')
    const r = await writeExport(dir, files)
    expect(r.deleted).toBe(1)
    expect(r.keptYours).toBeGreaterThan(0)
    expect(dir.read('Godot/Scripts/Classes/gameplay_player/health.gd')).toBe('# mine')
    expect(dir.read('Godot/Scripts/Generated/item_definition.gd.uid')).toBe('uid://abc')
    expect(dir.read('Localization/strings.csv.import')).toBe('[remap]')
    expect(dir.read('Localization/strings.en.translation')).toBe('binary')
    expect(dir.read('Godot/Scripts/Generated/old_definition.gd')).toBeUndefined()
    expect(dir.read('Godot/Scripts/Generated/old_definition.gd.uid')).toBeUndefined()
  })
})
