/** A GDScript expression making the input event for a planned key, mouse button or gamepad control; undefined when unknown. */
export function godotEvent(device: 'key' | 'mouse' | 'gamepad', text: string): string | undefined {
  const t = text.trim().toLowerCase()
  if (device === 'mouse') return MOUSE[t] && `_mouse(${MOUSE[t]})`
  if (device === 'gamepad') return PAD[t] ? `_joy(${PAD[t]})` : TRIGGERS[t] && `_axis(${TRIGGERS[t]})`
  if (/^[a-z]$/.test(t)) return `_key(KEY_${t.toUpperCase()})`
  if (/^[0-9]$/.test(t)) return `_key(KEY_${t})`
  if (/^f([1-9]|1[0-2])$/.test(t)) return `_key(KEY_${t.toUpperCase()})`
  return KEYS[t] && `_key(${KEYS[t]})`
}

const actionName = (words: string[]) => words.map((w) => w.toLowerCase()).join('_')

export function inputFile(ir: EngineIR, n: GodotNames): EmittedFile[] {
  const actions = ir.input.actions
  if (!actions.length) return []
  const cls = `${n.project}Input`
  const consts = actions.map((a) => `const ${n.identifier(a.words, 'constant')} := &${n.gdString(actionName(a.words))}`)
  const cases = actions.flatMap((a) => {
    const events = ([['key', a.key], ['mouse', a.mouse], ['gamepad', a.gamepad]] as const).flatMap(([d, t]) => (t && godotEvent(d, t) ? [godotEvent(d, t)!] : []))
    return [`\t\t${n.gdString(actionName(a.words))}:`, `\t\t\treturn [${events.join(', ')}]`]
  })
  const lines = [
    ...HEADER(ir, 'input map'),
    `class_name ${cls}`,
    'extends RefCounted',
    '## The plan’s controls (UI/UX › Controls) as input actions. The planner addon adds the missing ones to',
    '## Project Settings ▸ Input Map after an import; your own changes there are kept. Use Input.is_action_pressed(' + cls + '.JUMP).',
    '',
    ...consts,
    '',
    '## Category, mode and the screens an action is limited to, as planned.',
    'const INFO := {',
    ...actions.map((a) => `\t${n.gdString(actionName(a.words))}: { "name": ${n.gdString(a.name)}, "category": ${n.gdString(a.category)}, "mode": ${n.gdString(a.mode ?? '')}, "rebindable": ${a.rebindable}, "screens": [${a.contexts.map((c) => n.gdString(ir.ui.screens.find((s) => s.id === c)?.name ?? c)).join(', ')}] },`),
    '}',
    '',
    '',
    '## The planned events of an action.',
    'static func events(action: StringName) -> Array[InputEvent]:',
    '\tmatch str(action):',
    ...cases,
    '\treturn []',
    '',
    '',
    '## Adds every planned action that Project Settings does not have yet (editor only). Returns how many.',
    'static func register_project_settings() -> int:',
    '\tvar added := 0',
    '\tfor action in INFO:',
    '\t\tvar key := "input/" + str(action)',
    '\t\tif ProjectSettings.has_setting(key):',
    '\t\t\tcontinue',
    '\t\tProjectSettings.set_setting(key, { "deadzone": 0.5, "events": events(action) })',
    '\t\tadded += 1',
    '\tif added > 0:',
    '\t\tProjectSettings.save()',
    '\treturn added',
    '',
    '',
    'static func _key(code: Key) -> InputEvent:',
    '\tvar e := InputEventKey.new()',
    '\te.physical_keycode = code',
    '\treturn e',
    '',
    '',
    'static func _mouse(button: MouseButton) -> InputEvent:',
    '\tvar e := InputEventMouseButton.new()',
    '\te.button_index = button',
    '\treturn e',
    '',
    '',
    'static func _joy(button: JoyButton) -> InputEvent:',
    '\tvar e := InputEventJoypadButton.new()',
    '\te.button_index = button',
    '\treturn e',
    '',
    '',
    'static func _axis(axis: JoyAxis) -> InputEvent:',
    '\tvar e := InputEventJoypadMotion.new()',
    '\te.axis = axis',
    '\te.axis_value = 1.0',
    '\treturn e',
    '',
  ]
  return [{ path: `${GEN}${n.fileOf(cls)}.gd`, content: lines.join('\n') }]
}

