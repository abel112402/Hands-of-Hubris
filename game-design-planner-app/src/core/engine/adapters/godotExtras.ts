import type { EmittedFile, IdentKind } from '../adapter'
import type { FormulaNode } from '../formulaAst'
import type { EngineIR, IrSchema } from '../ir'
import type { IrCheat, IrParam } from '../irExtras'

/**
 * Godot output for the integration ideas (plans/UNITY_INTEGRATION_PLAN.md § 7), the counterparts of unityExtras.ts:
 * data checks (run by the planner addon's Validate), a debug console, the Architecture's channels (an event-bus autoload
 * and Resource channels), and typed telemetry. The addon registers the autoloads and makes the channel resources.
 */
export type GodotNames = {
  project: string
  schemaType(s: IrSchema): string
  field(s: IrSchema, planner: string): string
  identifier(words: string[], kind: IdentKind): string
  gdString(s: string): string
  fileOf(className: string): string
}

const HEADER = (ir: EngineIR, what: string) => ['# <auto-generated>', `#   Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name}”: ${what}.`, '#   Do not edit: the next export replaces this file.', '# </auto-generated>']
const doc = (s: string) => s.split('\n').map((l) => `## ${l}`.trimEnd())
export const GEN = 'Scripts/Generated/'

/** A parameter's GDScript type: records of a native schema as their resource type, of JSON/CSV schemas as their ID. */
function paramType(p: IrParam, ir: EngineIR, n: GodotNames): string {
  const t = p.type
  if (t.k === 'ref') {
    const s = ir.schemas.find((x) => x.id === t.schema)
    return s && s.format === 'native' ? n.schemaType(s) : 'String'
  }
  return t.k === 'string' ? 'String' : t.k
}
const paramNames = (ps: IrParam[], n: GodotNames) => {
  const used = new Set<string>()
  return ps.map((p) => {
    let name = n.identifier(p.words, 'param')
    for (let i = 2; used.has(name); i++) name = `${n.identifier(p.words, 'param')}${i}`
    used.add(name)
    return name
  })
}
const signature = (ps: IrParam[], ir: EngineIR, n: GodotNames) => {
  const names = paramNames(ps, n)
  return { names, sig: ps.map((p, i) => `${names[i]}: ${paramType(p, ir, n)}`).join(', ') }
}

// ---- Data checks ----

const PREC: Record<string, number> = { '+': 1, '-': 1, '*': 2, '/': 2 }
function expr(node: FormulaNode, field: (v: string) => string): string {
  const prec = (x: FormulaNode) => (x.k === 'bin' && x.op !== '^' ? PREC[x.op] : x.k === 'neg' ? 3 : 4)
  switch (node.k) {
    case 'num':
      return Number.isInteger(node.v) ? `${node.v}.0` : String(node.v)
    case 'var':
      return `float(r.${field(node.name)})`
    case 'neg':
      return prec(node.a) < 3 ? `-(${expr(node.a, field)})` : `-${expr(node.a, field)}`
    case 'call': {
      const a = node.args.map((x) => expr(x, field))
      // The planner rounds halves up; Godot's round goes away from zero.
      if (node.fn === 'round') return `floorf(${a[0]} + 0.5)`
      if (node.fn === 'min' || node.fn === 'max') return a.length === 2 ? `${node.fn}f(${a.join(', ')})` : `float(${node.fn}(${a.join(', ')}))`
      if (['abs', 'floor', 'ceil'].includes(node.fn)) return `${node.fn}f(${a[0]})`
      return `${node.fn}(${a.join(', ')})`
    }
    case 'bin': {
      if (node.op === '^') return `pow(${expr(node.a, field)}, ${expr(node.b, field)})`
      const p = PREC[node.op]
      const l = expr(node.a, field)
      const r = expr(node.b, field)
      return `${prec(node.a) < p ? `(${l})` : l} ${node.op} ${prec(node.b) < p || (prec(node.b) === p && (node.op === '-' || node.op === '/')) ? `(${r})` : r}`
    }
  }
}

/** Checks the addon can run: valid, on a native-format schema (its records are resources). */
export const godotChecks = (ir: EngineIR) => ir.checks.filter((c) => !c.error && c.ast && ir.schemas.find((s) => s.id === c.schema)?.format === 'native')

export function checksFile(ir: EngineIR, n: GodotNames): EmittedFile[] {
  const checks = godotChecks(ir)
  if (!checks.length) return []
  const cls = `${n.project}DataChecks`
  const list = checks.map((c) => {
    const s = ir.schemas.find((x) => x.id === c.schema)!
    const entries = [`"name": ${n.gdString(c.name)}`, `"schema": ${n.gdString(c.schema)}`, `"type": ${n.gdString(n.schemaType(s))}`, `"expr": ${n.gdString(c.expr)}`, `"level": ${n.gdString(c.level)}`]
    if (c.min !== undefined) entries.push(`"min": ${c.min}`)
    if (c.max !== undefined) entries.push(`"max": ${c.max}`)
    return `\t{ ${entries.join(', ')} },`
  })
  const cases = checks.flatMap((c, i) => {
    const s = ir.schemas.find((x) => x.id === c.schema)!
    return [`\t\t${i}:`, `\t\t\treturn ${expr(c.ast!, (f) => n.field(s, f))}`]
  })
  const lines = [
    ...HEADER(ir, 'data checks of the Balance plan'),
    `class_name ${cls}`,
    'extends RefCounted',
    '## The Balance plan’s data checks. The planner addon’s Validate runs them on every record resource and lists',
    '## the records outside the range (errors, or warnings for checks marked Warning).',
    '',
    'const CHECKS := [',
    ...list,
    ']',
    '',
    '',
    '## The value of check i for one record resource.',
    'static func value(i: int, r: Resource) -> float:',
    '\tmatch i:',
    ...cases,
    '\treturn NAN',
    '',
  ]
  return [{ path: `${GEN}${n.fileOf(cls)}.gd`, content: lines.join('\n') }]
}

// ---- Debug console ----

const snakeCommand = (c: IrCheat) => c.words.map((w) => w.toLowerCase()).join('_')

export function consoleFiles(ir: EngineIR, n: GodotNames): EmittedFile[] {
  if (!ir.cheats.length) return []
  const cls = `${n.project}Console`
  const lists = new Map<string, string[]>()
  for (const c of ir.cheats) for (const a of c.args) if (a.kind === 'id' && a.values) lists.set(a.name, a.values.map((v) => v.id))
  const help = ir.cheats.map((c) => `${c.command} ${c.args.map((a) => (a.optional ? `[${a.name}]` : `<${a.name}>`)).join(' ')}`.trim() + ` — ${c.help}`)
  const cases = ir.cheats.flatMap((c) => {
    const required = c.args.filter((a) => !a.optional).length
    const usage = `${c.command} ${c.args.map((a) => (a.optional ? `[${a.name}]` : `<${a.name}>`)).join(' ')}`.trim()
    const out = [`\t\t${n.gdString(c.command)}:`, `\t\t\tif parts.size() < ${required + 1}:`, `\t\t\t\treturn ${n.gdString(`Usage: ${usage}`)}`]
    const call: string[] = []
    c.args.forEach((a, i) => {
      const at = `parts[${i + 1}]`
      if (a.kind === 'id') {
        out.push(`\t\t\tvar a${i}: String = ${a.optional ? `${at} if parts.size() > ${i + 1} else ""` : at}`, `\t\t\tvar e${i} := _known(${n.gdString(a.name)}, a${i})`, `\t\t\tif e${i} != "":`, `\t\t\t\treturn e${i}`)
        call.push(`a${i}`)
      } else if (a.kind === 'int') {
        out.push(`\t\t\tvar a${i} := 1`, `\t\t\tif parts.size() > ${i + 1}:`, `\t\t\t\tif not ${at}.is_valid_int():`, `\t\t\t\t\treturn ${n.gdString(`${a.name} must be a whole number.`)}`, `\t\t\t\ta${i} = ${at}.to_int()`)
        call.push(`a${i}`)
      } else {
        out.push(`\t\t\tvar t${i} := ${at}.split(":")`, `\t\t\tif t${i}.size() != 2 or not t${i}[0].is_valid_int() or not t${i}[1].is_valid_int() or t${i}[0].to_int() > 23 or t${i}[1].to_int() > 59:`, `\t\t\t\treturn ${n.gdString('Time must be HH:MM, e.g. 18:30.')}`)
        call.push(`t${i}[0].to_int()`, `t${i}[1].to_int()`)
      }
    })
    out.push(`\t\t\treturn _call(${n.gdString(snakeCommand(c))}, [${call.join(', ')}], line)`)
    return out
  })
  const kinds = ir.cheats.map((c) => `\t${n.gdString(c.command)}: [${c.args.map((a) => (a.kind === 'id' ? n.gdString(a.name) : '""')).join(', ')}],`)
  const methods = ir.cheats.map((c) => `##   ${snakeCommand(c)}(${c.args.flatMap((a) => (a.kind === 'time' ? ['hour: int', 'minute: int'] : [`${a.name}: ${a.kind === 'int' ? 'int' : 'String'}`])).join(', ')})`)
  const console = [
    ...HEADER(ir, 'debug console'),
    `class_name ${cls}`,
    'extends RefCounted',
    '## Development console with the plan’s commands. run("give item.iron_sword 5") checks the command and its IDs',
    '## against the plan and calls the handler: set handler to an object of yours with these methods:',
    ...methods,
    '## The overlay (planner_console_overlay.gd, an autoload the addon adds) shows it in debug builds: ` opens it.',
    '',
    `const COMMANDS: Array[String] = [${help.map((h) => n.gdString(h)).join(', ')}]`,
    'const VALUES := {',
    ...[...lists].map(([k, v]) => `\t${n.gdString(k)}: [${v.map((x) => n.gdString(x)).join(', ')}],`),
    '}',
    '## The kind of each argument, per command ("" for a number or a time).',
    'const ARGS := {',
    ...kinds,
    '}',
    '',
    'static var handler: Object',
    '',
    '',
    '## Runs one command line; returns what happened, or why not.',
    'static func run(line: String) -> String:',
    '\tvar parts := line.strip_edges().split(" ", false)',
    '\tif parts.is_empty():',
    '\t\treturn ""',
    '\tmatch parts[0].to_lower():',
    '\t\t"help":',
    '\t\t\treturn "\\n".join(COMMANDS)',
    ...cases,
    '\treturn "Unknown command “%s”. Type help." % parts[0]',
    '',
    '',
    '## Completions for the last word: commands first, then the IDs the argument accepts.',
    'static func complete(line: String) -> PackedStringArray:',
    '\tvar parts := line.split(" ")',
    '\tvar last := parts[parts.size() - 1]',
    '\tvar out := PackedStringArray()',
    '\tif parts.size() == 1:',
    '\t\tfor c in ARGS.keys() + ["help"]:',
    '\t\t\tif str(c).begins_with(last):',
    '\t\t\t\tout.append(c)',
    '\t\treturn out',
    '\tvar kinds: Array = ARGS.get(parts[0], [])',
    '\tvar i := parts.size() - 2',
    '\tif i < kinds.size() and VALUES.has(kinds[i]):',
    '\t\tfor id in VALUES[kinds[i]]:',
    '\t\t\tif str(id).begins_with(last):',
    '\t\t\t\tout.append(id)',
    '\treturn out',
    '',
    '',
    'static func _known(kind: String, id: String) -> String:',
    '\tvar ids: Array = VALUES.get(kind, [])',
    '\tif id in ids:',
    '\t\treturn ""',
    '\tvar close := ids.filter(func(x): return str(x).contains(id)).slice(0, 3)',
    '\treturn "No %s “%s” in the plan.%s" % [kind, id, (" Did you mean %s?" % ", ".join(close)) if not close.is_empty() else ""]',
    '',
    '',
    'static func _call(method: String, args: Array, line: String) -> String:',
    '\tif handler == null or not handler.has_method(method):',
    '\t\treturn "No handler for %s: set %s.handler to an object with %s()." % [method, "' + cls + '", method]',
    '\thandler.callv(method, args)',
    '\treturn "OK: " + line.strip_edges()',
    '',
  ]
  const overlay = [
    ...HEADER(ir, 'debug console overlay'),
    'extends CanvasLayer',
    `## The ${cls} in the game (debug builds only): \` opens it, Enter runs, Tab completes, ↑ recalls.`,
    '## The planner addon adds this script as the autoload “PlannerConsole”.',
    '',
    'var _log: Label',
    'var _field: LineEdit',
    'var _history: PackedStringArray = []',
    '',
    '',
    'func _ready() -> void:',
    '\tlayer = 128',
    '\tif not OS.is_debug_build():',
    '\t\tset_process_input(false)',
    '\t\treturn',
    '\tvar box := VBoxContainer.new()',
    '\tbox.set_anchors_preset(Control.PRESET_TOP_WIDE)',
    '\t_log = Label.new()',
    '\t_field = LineEdit.new()',
    '\t_field.text_submitted.connect(_submit)',
    '\tbox.add_child(_log)',
    '\tbox.add_child(_field)',
    '\tadd_child(box)',
    '\tvisible = false',
    '',
    '',
    'func _input(event: InputEvent) -> void:',
    '\tif event is InputEventKey and event.pressed and not event.echo:',
    '\t\tif event.keycode == KEY_QUOTELEFT:',
    '\t\t\tvisible = not visible',
    '\t\t\tif visible:',
    '\t\t\t\t_field.grab_focus()',
    '\t\t\tget_viewport().set_input_as_handled()',
    '\t\telif visible and event.keycode == KEY_TAB:',
    `\t\t\tvar c := ${cls}.complete(_field.text)`,
    '\t\t\tif not c.is_empty():',
    '\t\t\t\tvar cut := _field.text.rfind(" ") + 1',
    '\t\t\t\t_field.text = _field.text.substr(0, cut) + c[0]',
    '\t\t\t\t_field.caret_column = _field.text.length()',
    '\t\t\tget_viewport().set_input_as_handled()',
    '\t\telif visible and event.keycode == KEY_UP and not _history.is_empty():',
    '\t\t\t_field.text = _history[_history.size() - 1]',
    '\t\t\tget_viewport().set_input_as_handled()',
    '',
    '',
    'func _submit(text: String) -> void:',
    '\tif text.strip_edges() == "":',
    '\t\treturn',
    '\t_history.append(text)',
    `\tvar lines := (_log.text + "\\n> " + text + "\\n" + ${cls}.run(text)).split("\\n")`,
    '\t_log.text = "\\n".join(lines.slice(max(0, lines.size() - 12)))',
    '\t_field.clear()',
    '',
  ]
  return [
    { path: `${GEN}${n.fileOf(cls)}.gd`, content: console.join('\n') },
    { path: `${GEN}planner_console_overlay.gd`, content: overlay.join('\n') },
  ]
}

// ---- Channels ----

export function channelFiles(ir: EngineIR, n: GodotNames): EmittedFile[] {
  const out: EmittedFile[] = []
  const docOf = (c: EngineIR['channels'][number]) => doc([`${c.name} (${c.kindLabel || 'channel'}${c.frequency ? `, ${c.frequency.toLowerCase()}` : ''}).`, c.publishers.length ? `Published by ${c.publishers.join(', ')}.` : '', c.subscribers.length ? `Listened to by ${c.subscribers.join(', ')}.` : ''].filter(Boolean).join(' '))
  const bus = ir.channels.filter((c) => c.kind === 'bus')
  if (bus.length) {
    const used = new Set<string>()
    const lines = [...HEADER(ir, 'event bus from the Architecture'), 'extends Node', '## The Architecture’s event-bus channels as signals. The planner addon adds this script as the autoload “GameEvents”:', '## GameEvents.need_changed.connect(_on_need_changed), GameEvents.need_changed.emit(npc_id, need_id, value).', '']
    for (const c of bus) {
      let name = n.identifier(c.words, 'field')
      for (let k = 2; used.has(name); k++) name = `${n.identifier(c.words, 'field')}${k}`
      used.add(name)
      lines.push(...docOf(c), `signal ${name}(${signature(c.payload, ir, n).sig})`, '')
    }
    out.push({ path: `${GEN}Channels/game_events.gd`, content: lines.join('\n') })
  }
  const used = new Set<string>()
  for (const c of ir.channels.filter((x) => x.kind === 'asset')) {
    let type = `${n.identifier(c.words, 'type')}Channel`
    for (let k = 2; used.has(type); k++) type = `${n.identifier(c.words, 'type')}${k}Channel`
    used.add(type)
    const s = signature(c.payload, ir, n)
    out.push({
      path: `${GEN}Channels/${n.fileOf(type)}.gd`,
      content: [
        ...HEADER(ir, 'Resource channel from the Architecture'),
        `class_name ${type}`,
        'extends Resource',
        ...docOf(c),
        '## The planner addon makes one resource of it under Channels/; share that resource between the nodes that talk.',
        '',
        `const CHANNEL_ID := ${n.gdString(c.id)}`,
        '',
        `signal raised(${s.sig})`,
        '',
        '',
        `func raise(${s.sig}) -> void:`,
        `\traised.emit(${s.names.join(', ')})`,
        '',
      ].join('\n'),
    })
  }
  return out
}

// ---- Telemetry ----

export function telemetryFile(ir: EngineIR, n: GodotNames): EmittedFile[] {
  if (!ir.telemetry.length) return []
  const cls = `${n.project}Telemetry`
  const used = new Set<string>(['enabled', 'clear'])
  const methods: string[] = []
  for (const t of ir.telemetry) {
    let m = n.identifier(t.words, 'method')
    for (let k = 2; used.has(m); k++) m = `${n.identifier(t.words, 'method')}${k}`
    used.add(m)
    const s = signature(t.params, ir, n)
    const values = t.params.map((p, i) => {
      const schema = p.type.k === 'ref' ? ir.schemas.find((x) => x.id === (p.type as { schema: string }).schema) : undefined
      const v = schema && schema.format === 'native' ? `${s.names[i]}.id if ${s.names[i]} != null else null` : s.names[i]
      return `${n.gdString(p.words.join('_'))}: ${v}`
    })
    const metrics = [`${t.key}.count`, ...t.params.filter((p) => p.type.k === 'int' || p.type.k === 'float').map((p) => `${t.key}.${p.words.join('_')}`)]
    methods.push('', '', ...doc([`${t.name}.`, t.notes, `Metrics: ${metrics.join(', ')}.`].filter(Boolean).join(' ')), `static func ${m}(${s.sig}) -> void:`, `\t_write(${n.gdString(t.key)}, {${values.join(', ')}})`)
  }
  const lines = [
    ...HEADER(ir, 'telemetry events of the Balance plan'),
    `class_name ${cls}`,
    'extends RefCounted',
    '## Playtest telemetry from the Balance plan: one typed call per event, each appending a JSON line to',
    '## user://hoh-telemetry.jsonl. The planner addon adds the lines up into metrics (<key>.count and the mean of each',
    '## number parameter) for the report. Set enabled = false to log nothing, e.g. in release builds.',
    '',
    'const FILE := "user://hoh-telemetry.jsonl"',
    '',
    'static var enabled := true',
    'static var _session := ""',
    ...methods,
    '',
    '',
    'static func _write(key: String, values: Dictionary) -> void:',
    '\tif not enabled:',
    '\t\treturn',
    '\tif _session == "":',
    '\t\t_session = "%x%x" % [randi(), Time.get_ticks_usec()]',
    '\tvar line := { "event": key, "t": Time.get_datetime_string_from_system(true) + "Z", "session": _session, "build": str(ProjectSettings.get_setting("application/config/version", "")) }',
    '\tline.merge(values)',
    '\tvar f := FileAccess.open(FILE, FileAccess.READ_WRITE) if FileAccess.file_exists(FILE) else FileAccess.open(FILE, FileAccess.WRITE)',
    '\tif f == null:',
    '\t\tpush_warning("Telemetry: cannot write %s" % FILE)',
    '\t\treturn',
    '\tf.seek_end()',
    '\tf.store_line(JSON.stringify(line))',
    '',
  ]
  return [{ path: `${GEN}${n.fileOf(cls)}.gd`, content: lines.join('\n') }]
}
