import type { EmittedFile } from '../adapter'
import type { EngineIR } from '../ir'
import { GEN, type GodotNames } from './godotExtras'

/**
 * Godot output for the polish ideas (plans/UNITY_INTEGRATION_PLAN.md § 7), the counterparts of unityPolish.ts: a
 * sampler for the performance budgets (I10: an autoload the addon registers) and audio events from Audio Direction
 * (I12: the addon makes one resource per event). The pseudo-locale (I15) is Godot's own pseudolocalization, which the
 * addon sets up; the architecture guard (I18) is ProjectFiles/architecture.json, checked by the addon's Validate.
 */

const HEADER = (ir: EngineIR, what: string) => ['# <auto-generated>', `#   Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name}”: ${what}.`, '#   Do not edit: the next export replaces this file.', '# </auto-generated>']
const doc = (s: string) => s.split('\n').map((l) => `## ${l}`.trimEnd())

// ---- I10: performance budgets ----

/** Godot's own monitors; batches have none, so the game records them like any other budget. */
const MONITORS: Record<string, string> = {
  memory: 'Performance.MEMORY_STATIC',
  drawCalls: 'Performance.RENDER_TOTAL_DRAW_CALLS_IN_FRAME',
  triangles: 'Performance.RENDER_TOTAL_PRIMITIVES_IN_FRAME',
}
const memoryScale = (unit: string) => (/^g/i.test(unit) ? ' / 1073741824.0' : /^m/i.test(unit) ? ' / 1048576.0' : /^k/i.test(unit) ? ' / 1024.0' : '')

export function budgetFile(ir: EngineIR, n: GodotNames): EmittedFile[] {
  const budgets = ir.budgets
  if (!budgets.length) return []
  const used = new Set<string>(['FILE'])
  const consts = budgets.map((b) => {
    let c = n.identifier(b.words, 'constant')
    for (let k = 2; used.has(c); k++) c = `${n.identifier(b.words, 'constant')}_${k}`
    used.add(c)
    return c
  })
  const recorded = budgets.filter((b) => b.probe === 'custom' || b.probe === 'batches')
  const example = recorded[0] ? consts[budgets.indexOf(recorded[0])] : consts[0]
  const samples = budgets.flatMap((b) => {
    if (b.probe === 'frameTime') return [`\trecord(${n.gdString(b.key)}, frame_ms)`]
    const m = MONITORS[b.probe]
    return m ? [`\trecord(${n.gdString(b.key)}, Performance.get_monitor(${m})${b.probe === 'memory' ? memoryScale(b.unit) : ''})`] : []
  })
  const lines = [
    ...HEADER(ir, 'performance budgets'),
    'extends Node',
    ...doc([
      'Measures the planned performance budgets (Technical › Performance) while the game runs, in debug builds and the',
      'editor: frame time, memory, draw calls and triangles by itself; the others when the game calls',
      `PlannerBudgets.record(PlannerBudgets.${example}, ms). The planner addon adds this script as the autoload`,
      '“PlannerBudgets”. The mean, minimum and maximum per key go to user://hoh-planner-budgets.json when the game quits;',
      'the addon puts them into the report, and the planner compares them with the budgets.',
    ].join('\n')),
    '',
    'const FILE := "user://hoh-planner-budgets.json"',
    '',
    ...budgets.flatMap((b, i) => [...doc(`${b.name}${b.platform ? ` (${b.platform})` : ''}: ${b.metric || b.probe}${b.target !== undefined ? `, target ${b.target} ${b.unit}` : ''}.`), `const ${consts[i]} := ${n.gdString(b.key)}`]),
    '',
    'var _data := {}',
    'var _warm_up := 2.0',
    'var _last_usec := 0',
    '',
    '',
    'func _ready() -> void:',
    '\tprocess_mode = Node.PROCESS_MODE_ALWAYS',
    '\tif not OS.is_debug_build():',
    '\t\tset_process(false)',
    '',
    '',
    '## Adds one sample under a budget key (for the budgets the sampler cannot measure by itself).',
    'func record(key: String, value: float) -> void:',
    '\tif key == "" or is_nan(value) or is_inf(value):',
    '\t\treturn',
    '\tvar m: Dictionary = _data.get_or_add(key, { "key": key, "samples": 0, "sum": 0.0, "min": value, "max": value })',
    '\tm["samples"] += 1',
    '\tm["sum"] += value',
    '\tm["min"] = minf(m["min"], value)',
    '\tm["max"] = maxf(m["max"], value)',
    '',
    '',
    'func _process(_delta: float) -> void:',
    '\t# Real time between frames (not scaled by Engine.time_scale); the first seconds (loading) are left out.',
    '\tvar now := Time.get_ticks_usec()',
    '\tvar frame_ms := (now - _last_usec) / 1000.0',
    '\tvar first := _last_usec == 0',
    '\t_last_usec = now',
    '\tif first:',
    '\t\treturn',
    '\t_warm_up -= frame_ms / 1000.0',
    '\tif _warm_up > 0.0:',
    '\t\treturn',
    ...(samples.length ? samples : ['\tpass']),
    '',
    '',
    'func _exit_tree() -> void:',
    '\tsave()',
    '',
    '',
    '## Adds this session’s samples to the file (summed with the sessions before).',
    'func save() -> void:',
    '\tif _data.is_empty():',
    '\t\treturn',
    '\tvar store := {}',
    '\tif FileAccess.file_exists(FILE):',
    '\t\tvar parsed: Variant = JSON.parse_string(FileAccess.get_file_as_string(FILE))',
    '\t\tif parsed is Dictionary:',
    '\t\t\tfor m in parsed.get("metrics", []):',
    '\t\t\t\tif m is Dictionary and str(m.get("key", "")) != "":',
    '\t\t\t\t\tstore[str(m["key"])] = m',
    '\tvar build := str(ProjectSettings.get_setting("application/config/version", ""))',
    '\tfor key in _data:',
    '\t\tvar s: Dictionary = _data[key]',
    '\t\tvar old: Dictionary = store.get_or_add(key, { "key": key, "samples": 0, "sum": 0.0, "min": s["min"], "max": s["max"] })',
    '\t\told["samples"] = int(old["samples"]) + int(s["samples"])',
    '\t\told["sum"] = float(old["sum"]) + float(s["sum"])',
    '\t\told["min"] = minf(float(old["min"]), s["min"])',
    '\t\told["max"] = maxf(float(old["max"]), s["max"])',
    '\t\told["build"] = build',
    '\t\told["lastAt"] = Time.get_datetime_string_from_system(true) + "Z"',
    '\tvar f := FileAccess.open(FILE, FileAccess.WRITE)',
    '\tif f != null:',
    '\t\tf.store_string(JSON.stringify({ "metrics": store.values() }, "  "))',
    '\t_data.clear()',
    '',
  ]
  return [{ path: `${GEN}Perf/planner_budgets.gd`, content: lines.join('\n') }]
}

// ---- I12: audio events ----

export const audioClasses = (n: GodotNames) => ({ event: `${n.project}AudioEvent`, list: `${n.project}AudioEvents` })

export function audioFiles(ir: EngineIR, n: GodotNames): EmittedFile[] {
  const events = ir.audio.events
  if (!events.length) return []
  const { event, list } = audioClasses(n)
  const res = [
    ...HEADER(ir, 'audio event'),
    `class_name ${event}`,
    'extends Resource',
    ...doc([
      'One sound of the plan (Audio Direction › Music / Sound effects): the streams you assign, and the planned volume,',
      'pitch variation, looping and 3D setting. The planner addon makes one resource per event under Audio/ and keeps the',
      'planned values in step; the streams are yours. Play it on an AudioStreamPlayer (2D/3D for spatial events).',
    ].join('\n')),
    '',
    'enum Kind { MUSIC, SFX }',
    '',
    '@export var planner_id := ""',
    '@export var kind := Kind.SFX',
    '## Assign one or more; play() picks one at random.',
    '@export var streams: Array[AudioStream] = []',
    '@export_range(0.0, 1.0) var volume := 1.0',
    '## ± fraction of pitch, picked per play.',
    '@export_range(0.0, 0.5) var pitch_variation := 0.0',
    '@export var loop := false',
    '@export var spatial := false',
    '@export_multiline var notes := ""',
    '',
    '',
    '## Plays one of the streams on an AudioStreamPlayer, AudioStreamPlayer2D or AudioStreamPlayer3D with the planned settings.',
    'func play(player: Node) -> void:',
    '\tif player == null or streams.is_empty():',
    '\t\treturn',
    '\tif not (player is AudioStreamPlayer or player is AudioStreamPlayer2D or player is AudioStreamPlayer3D):',
    '\t\tpush_warning("%s: play() needs an AudioStreamPlayer, not %s." % [resource_path, player.get_class()])',
    '\t\treturn',
    '\tif spatial and player is AudioStreamPlayer:',
    '\t\tpush_warning("%s is planned as 3D sound; play it on an AudioStreamPlayer2D or 3D." % resource_path)',
    '\tvar stream: AudioStream = streams.pick_random()',
    '\tif loop and "loop" in stream and not stream.get("loop"):',
    '\t\t# Ogg and MP3 streams loop by a property; set it on a copy so the imported stream stays as it is.',
    '\t\tstream = stream.duplicate()',
    '\t\tstream.set("loop", true)',
    '\tplayer.set("stream", stream)',
    '\tplayer.set("volume_db", linear_to_db(volume))',
    '\tplayer.set("pitch_scale", 1.0 + randf_range(-pitch_variation, pitch_variation))',
    '\tplayer.call("play")',
    '',
  ]
  const used = new Set<string>()
  const files = events.map((e) => {
    const base = e.words.map((w) => w.toLowerCase()).join('_') || 'sound'
    let f = base
    for (let i = 2; used.has(f); i++) f = `${base}_${i}`
    used.add(f)
    return f
  })
  const table = [
    ...HEADER(ir, 'audio events of Audio Direction'),
    `class_name ${list}`,
    'extends RefCounted',
    `## The planned audio events (Audio Direction), as the planner addon turns them into ${event} resources under Audio/.`,
    '',
    `const EVENT := preload(${n.gdString(`${n.fileOf(event)}.gd`)})`,
    '',
    'const ALL := [',
    ...events.map((e, i) => `\t{ "id": ${n.gdString(e.id)}, "file": ${n.gdString(files[i])}, "name": ${n.gdString(e.name)}, "kind": "${e.kind}", "volume": ${e.volume}, "pitch": ${e.pitch}, "loop": ${e.loop}, "spatial": ${e.spatial}, "notes": ${n.gdString([e.notes, e.when.length ? `Plays: ${e.when.join(', ')}.` : ''].filter(Boolean).join(' '))} },`),
    ']',
    '',
  ]
  return [
    { path: `${GEN}Audio/${n.fileOf(event)}.gd`, content: res.join('\n') },
    { path: `${GEN}Audio/${n.fileOf(list)}.gd`, content: table.join('\n') },
  ]
}

/** Global class names this file adds, for the adapter's clash check. */
export const polishGlobals = (ir: EngineIR, n: GodotNames) => (ir.audio.events.length ? Object.values(audioClasses(n)) : [])
