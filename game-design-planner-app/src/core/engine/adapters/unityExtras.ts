/**
 * Unity output for the integration ideas (plans/UNITY_INTEGRATION_PLAN.md § 7):
 * I6 — Balance plan data checks as EditMode tests that check the ScriptableObject assets themselves;
 * I5 — a debug console whose commands and accepted IDs come from the plan.
 */
export type UnityNames = {
  /** Root namespace of the generated code (its assembly's name too). */
  root: string
  /** Namespace of the generated data types. */
  ns: string
  schemaType(s: IrSchema): string
  /** C# field name of a schema's planner field. */
  field(s: IrSchema, planner: string): string
  identifier(words: string[]): string
  csString(s: string): string
}

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const HEADER = (ir: EngineIR, what: string) => ['// <auto-generated>', `//   Generated by Game Design Planner (engine IR v${ir.v}) from “${ir.project.name}”: ${what}.`, '//   Do not edit: the next import overwrites this file.', '// </auto-generated>']

// ---- I6: data checks → EditMode tests ----

const PREC: Record<string, number> = { '+': 1, '-': 1, '*': 2, '/': 2 }
const FUNC: Record<string, string> = { min: 'Mathf.Min', max: 'Mathf.Max', sqrt: 'Mathf.Sqrt', abs: 'Mathf.Abs', floor: 'Mathf.Floor', ceil: 'Mathf.Ceil', pow: 'Mathf.Pow', log: 'Mathf.Log' }
/** The check's expression in C#, over the asset's fields (as float). Rounding as in the planner: halves up. */
function expr(n: FormulaNode, field: (v: string) => string): string {
  const prec = (x: FormulaNode) => (x.k === 'bin' && x.op !== '^' ? PREC[x.op] : x.k === 'neg' ? 3 : 4)
  switch (n.k) {
    case 'num':
      return `${n.v}f`
    case 'var':
      return `(float)a.${field(n.name)}`
    case 'neg':
      return prec(n.a) < 3 ? `-(${expr(n.a, field)})` : `-${expr(n.a, field)}`
    case 'call':
      if (n.fn === 'round') return `Mathf.Floor(${expr(n.args[0], field)} + 0.5f)`
      return `${FUNC[n.fn]}(${n.args.map((a) => expr(a, field)).join(', ')})`
    case 'bin': {
      if (n.op === '^') return `Mathf.Pow(${expr(n.a, field)}, ${expr(n.b, field)})`
      const p = PREC[n.op]
      const l = expr(n.a, field)
      const r = expr(n.b, field)
      return `${prec(n.a) < p ? `(${l})` : l} ${n.op} ${prec(n.b) < p || (prec(n.b) === p && (n.op === '-' || n.op === '/')) ? `(${r})` : r}`
    }
  }
}

/** Checks the tests can run: valid, on a native-format schema (its records are assets). */
export const testableChecks = (ir: EngineIR) => ir.checks.filter((c) => !c.error && c.ast && ir.schemas.find((s) => s.id === c.schema)?.format === 'native')

function checkTest(c: IrCheck, ir: EngineIR, n: UnityNames, method: string): string[] {
  const s = ir.schemas.find((x) => x.id === c.schema)!
  const type = n.schemaType(s)
  const cond = [c.min !== undefined ? `v >= ${c.min}f` : '', c.max !== undefined ? `v <= ${c.max}f` : ''].filter(Boolean).join(' && ')
  const range = `${c.min ?? '−∞'}–${c.max ?? '∞'}`
  return [
    `/// <summary>${xml(`${c.name}: ${c.expr} in ${range} for every ${s.name}.`)}</summary>`,
    '[Test]',
    `public void ${method}()`,
    '{',
    '    var outside = new List<string>();',
    '    var checkedCount = 0;',
    `    foreach (var a in Assets<${type}>())`,
    '    {',
    '        checkedCount++;',
    `        var v = ${expr(c.ast!, (f) => n.field(s, f))};`,
    `        if (!(float.IsFinite(v) && ${cond})) outside.Add($"{a.id} = {v}");`,
    '    }',
    `    if (checkedCount == 0) Assert.Ignore(${n.csString(`No ${type} assets yet: import the planner export.`)});`,
    `    var message = ${n.csString(`${c.name} (${c.expr}) outside ${range}: `)} + string.Join(", ", outside);`,
    // A warning-level check never fails the run (Unity's NUnit has no Assert.Warn): it logs and passes with the message.
    c.level === 'warning' ? '    if (outside.Count > 0) { Debug.LogWarning(message); Assert.Pass(message); }' : '    if (outside.Count > 0) Assert.Fail(message);',
    '}',
  ]
}

export function checkFiles(ir: EngineIR, n: UnityNames): EmittedFile[] {
  const checks = testableChecks(ir)
  if (!checks.length) return []
  const methods: string[] = []
  const used = new Set<string>()
  for (const c of checks) {
    let m = n.identifier(c.words).replace(/^@/, '') || 'Check'
    for (let i = 2; used.has(m); i++) m = `${n.identifier(c.words).replace(/^@/, '')}${i}`
    used.add(m)
    methods.push(m)
  }
  const body = [
    '/// <summary>The Balance plan’s data checks, run on the record assets (Window ▸ General ▸ Test Runner ▸ EditMode).</summary>',
    'public class PlannerDataChecks',
    '{',
    '    private static IEnumerable<T> Assets<T>() where T : ScriptableObject =>',
    '        AssetDatabase.FindAssets("t:" + typeof(T).Name).Select(g => AssetDatabase.LoadAssetAtPath<T>(AssetDatabase.GUIDToAssetPath(g))).Where(a => a != null);',
    '',
    ...checks.flatMap((c, i) => [...checkTest(c, ir, n, methods[i]).map((l) => '    ' + l), '']),
  ]
  body.pop()
  body.push('}')
  const code = [...HEADER(ir, 'data checks of the Balance plan'), 'using System.Collections.Generic;', 'using System.Linq;', 'using NUnit.Framework;', 'using UnityEditor;', 'using UnityEngine;', `using ${n.ns};`, '', `namespace ${n.root}.PlannerTests`, '{', ...body.map((l) => (l ? '    ' + l : l)), '}', ''].join('\n')
  const asmdef = {
    name: `${n.root}.PlannerTests`,
    rootNamespace: `${n.root}.PlannerTests`,
    references: [n.root, 'UnityEngine.TestRunner', 'UnityEditor.TestRunner'],
    includePlatforms: ['Editor'],
    overrideReferences: true,
    precompiledReferences: ['nunit.framework.dll'],
    autoReferenced: false,
    defineConstraints: ['UNITY_INCLUDE_TESTS'],
  }
  return [
    { path: `Tests/Editor/${n.root}.PlannerTests.asmdef`, content: JSON.stringify(asmdef, null, 2) + '\n' },
    { path: 'Tests/Editor/PlannerDataChecks.cs', content: code },
  ]
}

// ---- I5: debug console ----

const pascalCommand = (c: IrCheat) => c.words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('')
const argType = (a: IrCheat['args'][number]) => (a.kind === 'int' ? 'int' : 'string')
const handlerParams = (c: IrCheat) => c.args.flatMap((a) => (a.kind === 'time' ? ['int hour', 'int minute'] : [`${argType(a)} ${a.name}`])).join(', ')

function runCase(c: IrCheat, n: UnityNames): string[] {
  const required = c.args.filter((a) => !a.optional).length
  const usage = `${c.command} ${c.args.map((a) => (a.optional ? `[${a.name}]` : `<${a.name}>`)).join(' ')}`.trim()
  const out = [`case ${n.csString(c.command)}:`, '{', `    if (parts.Length < ${required + 1}) return ${n.csString(`Usage: ${usage}`)};`]
  const call: string[] = []
  c.args.forEach((a, i) => {
    const at = `parts[${i + 1}]`
    const v = `a${i}`
    if (a.kind === 'id') {
      out.push(`    var ${v} = ${a.optional ? `parts.Length > ${i + 1} ? ${at} : ""` : at};`, `    if (!Known(${n.csString(a.name)}, ${v}, out var e${i})) return e${i};`)
      call.push(v)
    } else if (a.kind === 'int') {
      out.push(`    var ${v} = 1;`, `    if (parts.Length > ${i + 1} && !int.TryParse(${at}, out ${v})) return ${n.csString(`${a.name} must be a whole number.`)};`)
      call.push(v)
    } else {
      out.push(`    if (!TryTime(${at}, out var h${i}, out var m${i})) return ${n.csString('Time must be HH:MM, e.g. 18:30.')};`)
      call.push(`h${i}`, `m${i}`)
    }
  })
  out.push('    if (Handler == null) return NoHandler;', `    Handler.${pascalCommand(c)}(${call.join(', ')});`, `    return "OK: " + line.Trim();`, '}')
  return out
}

