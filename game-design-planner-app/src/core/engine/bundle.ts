/** Builds the full export for one engine: IR, checks, manifest and every file, in a stable order. An engine without an adapter gets the engine-neutral part only. */
export function buildBundle(p: Project, engine: EngineId, exportedAt = new Date().toISOString()): EngineBundle {
  const adapter = getAdapter(engine)
  const { ir, issues: irIssues } = buildIR(p)
  const issues = [...irIssues, ...(adapter?.checks(ir) ?? [])].sort((a, b) => LEVEL_ORDER[a.level] - LEVEL_ORDER[b.level])
  const folders = schemaFolders(ir)
  const data = dataFiles(ir, folders)
  const maps = mapFiles(p)
  const files: EmittedFile[] = [
    { path: 'README.md', content: readme(ir, engine, adapter, ir.schemas) },
    { path: 'hoh-engine.schema.json', content: json(manifestJsonSchema()) },
    { path: 'ir/engine-ir.json', content: json(ir) },
    ...data.files,
    ...(ir.strings.length ? [{ path: 'Localization/strings.csv', content: csv([['key', 'en'], ...ir.strings.map((s) => [s.key, s.text])]) }] : []),
    ...maps,
    ...(adapter?.emit(ir).map((f) => ({ path: `${adapter.root}/${f.path}`, content: f.content })) ?? []),
  ]
  if (adapter?.sidecars) files.push(...adapter.sidecars(files.map((f) => f.path)))
  const manifest: EngineManifest = {
    format: ENGINE_FORMAT,
    v: ENGINE_FORMAT_VERSION,
    engine: { id: engine, adapterVersion: adapter?.version ?? 0 },
    generator: { app: 'Game Design Planner', version: APP_VERSION },
    project: { name: ir.project.name },
    exportedAt,
    schemas: ir.schemas.map((s) => ({
      id: s.id,
      name: s.name,
      format: s.format,
      idPrefix: s.idPrefix,
      version: s.version,
      records: ir.records.filter((r) => r.schema === s.id).length,
      data: data.paths.get(s.id)!,
      ...(s.load && { load: s.load }),
    })),
    counts: { records: ir.records.length, enums: ir.enums.length, formulas: ir.formulas.length, strings: ir.strings.length, maps: maps.length },
    files: files.map((f) => ({ path: f.path, hash: fnv1a(f.content) })),
  }
  return { ir, issues, manifest, files: [{ path: 'hoh-engine.json', content: json(manifest) }, ...files] }
}

/** The bundle as a zip under BUNDLE_ROOT. File dates are fixed so the same export gives the same bytes. */
export function bundleZip(b: EngineBundle): Promise<Blob> {
  const zip = new JSZip()
  const date = new Date(Date.UTC(2020, 0, 1))
  for (const f of b.files) zip.file(`${BUNDLE_ROOT}/${f.path}`, f.content, { date })
  return zip.generateAsync({ type: 'blob' })
}
